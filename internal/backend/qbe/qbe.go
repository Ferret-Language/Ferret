// qbeValueNeedsCopy reports whether a MIR value produces a bare operand
// (register, constant, or global reference) when lowered. In QBE the RHS of
// an assignment must be an instruction, so bare operands require "copy".
// Instructions like add/sub/call already carry their opcode and must not be
// wrapped.
func qbeValueNeedsCopy(v mir.Value) bool {
	switch v.(type) {
	case *mir.LocalValue, *mir.NameValue,
		*mir.NumberValue, *mir.BoolValue,
		*mir.NoneValue, *mir.AddrOfValue,
		*mir.TypeTestValue:
		return true
	}
	return false
}

func qbeSymbol(state *moduleState, path []string) string {
	if len(path) == 0 {
		return ""
	}
	if len(path) == 1 {
		name := sanitizeIdent(path[0])
		if state != nil {
			if _, ok := state.functions[path[0]]; ok {
				// Entry module: emit $main directly so the C runtime can call it
				// without an additional wrapper.
				if name == "main" && state.modulePrefix == "main" {
					return "main"
				}
				return state.modulePrefix + "__" + name
			}
			if _, ok := state.globals[path[0]]; ok {
				return state.modulePrefix + "__" + name
			}
		}
		return name
	}
	clean := make([]string, 0, len(path))
	for _, part := range path {
		clean = append(clean, sanitizeIdent(part))
	}
	return strings.Join(clean, "__")
}

func qbeTypeName(state *moduleState, named *typeinfo.NamedType) string {
	if named == nil {
		return "type"
	}
	moduleKey := named.ModuleKey
	if moduleKey == "" && state != nil && state.mod != nil {
		moduleKey = state.mod.Key
	}
	prefix := sanitizePath(moduleKey)
	if prefix == "" {
		prefix = state.modulePrefix
	}
	return prefix + "__" + sanitizeIdent(named.Name)
}

func qbeBlockLabel(fn *mir.Function, id int) string {
	if fn != nil && id == fn.EntryID {
		return "@entry"
	}
	return fmt.Sprintf("@bb%d", id)
}

func qbeLocalName(name string) string {
	if name == "" {
		return "%tmp"
	}
	return "%" + sanitizeIdent(name)
}

func freshTemp(state *moduleState, prefix string) string {
	state.nextTemp++
	return fmt.Sprintf("%%_%s%d", prefix, state.nextTemp)
}

func qbeFreshLabel(state *moduleState, prefix string) string {
	state.nextTemp++
	return fmt.Sprintf("@__%s%d", prefix, state.nextTemp)
}

func normalizeQBEAlign(align int64) int64 {
	switch {
	case align <= 4:
		return 4
	case align <= 8:
		return 8
	default:
		return 16
	}
}

// SanitizePath converts a module import path into the module prefix used in
// QBE symbol names, e.g. "math/vec2" → "math__vec2".
func SanitizePath(path string) string {
	return sanitizePath(path)
}

// FunctionReturnQBEType returns the QBE base type letter for the function's
// return type ("w", "l", "s", "d") or "" for void/unknown.
func FunctionReturnQBEType(fn *mir.Function) string {
	if fn == nil || fn.Result == nil {
		return ""
	}
	base, err := qbeBaseType(fn.Result)
	if err != nil {
		return ""
	}
	return base
}

func sanitizePath(path string) string {
	parts := strings.FieldsFunc(path, func(r rune) bool {
		switch r {
		case '/', ':', '.', '-', ' ':
			return true
		default:
			return false
		}
	})
	if len(parts) == 0 {
		return "mod"
	}
	for i := range parts {
		parts[i] = sanitizeIdent(parts[i])
	}
	return strings.Join(parts, "__")
}

func sanitizeIdent(s string) string {
	if s == "" {
		return "_"
	}
	var b strings.Builder
	for i, r := range s {
		ok := (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '_' || (i > 0 && r >= '0' && r <= '9')
		if ok {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	out := b.String()
	if out == "" {
		return "_"
	}
	return out
}

func unwrapNamed(t typeinfo.Type) typeinfo.Type {
	if named, ok := t.(*typeinfo.NamedType); ok && named != nil && named.Decl != nil {
		switch named.Decl.Type.(type) {
		case *ast.EnumType, *ast.ErrorType:
			return &typeinfo.BuiltinType{Name: "i32"}
		}
	}
	return t
}

type typeStringer struct {
	t typeinfo.Type
}

func (s typeStringer) String() string {
	if s.t == nil {
		return "void"
	}
	return s.t.String()
}
