const VendoredCommit = "8ff06515526c97628b47d8223b73d5376287a9b4"

//go:embed qbe-src
var sourceTree embed.FS

type lowerer struct{}

type moduleState struct {
	mod               *mir.Module
	layout            *layout.Module
	layouts           map[string]*layout.Module
	modules           map[string]*mir.Module
	fn                *mir.Function
	functions         map[string]struct{}
	globals           map[string]struct{}
	modulePrefix      string
	aggLocals         map[int]*aggregateLocal
	aggParams         map[int]struct{}
	scalarLocals      map[int]*scalarAllocaLocal
	nextTemp          int
	nextStrConst      int              // counter for unnamed string constant globals
	deferredB         *strings.Builder // deferred data sections (string literals used in functions)
	pendingLines      []string
	interfaceVTables  map[string]string
	interfaceWrappers map[string]struct{}
	tempValues        map[int]mir.Value
}

type aggregateLocal struct {
	ID      int
	Name    string
	Type    typeinfo.Type
	Size    int64
	Align   int64
	PtrName string
}

type scalarAllocaLocal struct {
	ID      int
	Name    string
	Type    typeinfo.Type
	PtrName string
	QType   string
	Size    int64
	Align   int64
}

func New() backend.Lowerer { return &lowerer{} }

func (*lowerer) Target() backend.Target { return backend.TargetQBE }

func (*lowerer) LowerModule(unit *backend.Unit) (*backend.Artifact, error) {
	if err := backend.ValidateUnit(unit); err != nil {
		return nil, err
	}
	state := &moduleState{
		mod:               unit.Module,
		layout:            unit.Layout,
		layouts:           unit.Layouts,
		modules:           unit.Modules,
		functions:         make(map[string]struct{}),
		globals:           make(map[string]struct{}),
		modulePrefix:      sanitizePath(unit.Module.ImportPath),
		deferredB:         &strings.Builder{},
		interfaceVTables:  make(map[string]string),
		interfaceWrappers: make(map[string]struct{}),
		tempValues:        make(map[int]mir.Value),
	}
	for _, fn := range unit.Module.Functions {
		if fn != nil {
			state.functions[fn.Name] = struct{}{}
		}
	}
	for _, g := range unit.Module.Globals {
		if g != nil {
			state.globals[g.Name] = struct{}{}
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# generated by ferret qbe backend\n")
	fmt.Fprintf(&b, "# vendored qbe commit: %s\n\n", VendoredCommit)
	if err := emitTypes(&b, state, unit.Module.Types); err != nil {
		return nil, err
	}
	if len(unit.Module.Types) > 0 && (len(unit.Module.Globals) > 0 || len(unit.Module.Functions) > 0) {
		b.WriteByte('\n')
	}
	if err := emitGlobals(&b, state, unit.Module.Globals); err != nil {
		return nil, err
	}
	if len(unit.Module.Globals) > 0 && len(unit.Module.Functions) > 0 {
		b.WriteByte('\n')
	}
	written := 0
	for _, fn := range unit.Module.Functions {
		if fn == nil || fn.IsBuiltin || fn.IsExtern {
			continue
		}
		if written > 0 {
			b.WriteByte('\n')
		}
		if err := emitFunction(&b, state, fn); err != nil {
			return nil, err
		}
		written++
	}
	// Flush any string-literal data sections emitted during function lowering.
	if state.deferredB.Len() > 0 {
		b.WriteByte('\n')
		b.WriteString(state.deferredB.String())
	}
	return &backend.Artifact{
		Target:    backend.TargetQBE,
		ModuleKey: unit.Module.Key,
		FileExt:   ".qbe",
		Text:      b.String(),
	}, nil
}

func SourceFS() fs.FS {
	root, err := fs.Sub(sourceTree, "qbe-src")
	if err != nil {
		panic(err)
	}
	return root
}

func emitTypes(b *strings.Builder, state *moduleState, types []*mir.TypeDecl) error {
	// Always emit the built-in slice aggregate type used for str.
	b.WriteString("type :__ferret_slice = { l, l }\n")
	seen := make(map[string]struct{})
	lines := make([]string, 0)
	emitDecls := func(decls []*mir.TypeDecl) error {
		for _, decl := range decls {
			if decl == nil || decl.Named == nil || (decl.Struct == nil && decl.Union == nil && decl.Interface == nil) {
				continue
			}
			key := decl.Named.ModuleKey + "::" + decl.Name
			if _, ok := seen[key]; ok {
				continue
			}
			line, err := lowerTypeDecl(state, decl)
			if err != nil {
				return err
			}
			if line == "" {
				continue
			}
			seen[key] = struct{}{}
			lines = append(lines, line)
		}
		return nil
	}
	if err := emitDecls(types); err != nil {
		return err
	}
	if state.modules != nil {
		keys := make([]string, 0, len(state.modules))
		for key := range state.modules {
			if state.mod != nil && key == state.mod.Key {
				continue
			}
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			if err := emitDecls(state.modules[key].Types); err != nil {
				return err
			}
		}
	}
	for i, line := range lines {
		if i > 0 {
			b.WriteByte('\n')
		}
		b.WriteString(line)
		b.WriteByte('\n')
	}
	return nil
}

func lowerTypeDecl(state *moduleState, decl *mir.TypeDecl) (string, error) {
	layoutInfo, err := lookupNamedLayout(state, decl.Named)
	if err != nil {
		return "", err
	}
	if layoutInfo == nil || !layoutInfo.Known {
		return "", fmt.Errorf("type %s: unknown layout", decl.Name)
	}
	if decl.Struct != nil {
		if layoutInfo.Struct == nil {
			return "", fmt.Errorf("type %s: unknown struct layout", decl.Name)
		}
		body, err := qbeStructBody(state, layoutInfo.Struct)
		if err != nil {
			return "", fmt.Errorf("type %s: %w", decl.Name, err)
		}
		return fmt.Sprintf("type :%s = { %s }", qbeTypeName(state, decl.Named), body), nil
	}
	if decl.Union != nil {
		if layoutInfo.Align > 1 {
			return fmt.Sprintf("type :%s = align %d { %d }", qbeTypeName(state, decl.Named), layoutInfo.Align, layoutInfo.Size), nil
		}
		return fmt.Sprintf("type :%s = { %d }", qbeTypeName(state, decl.Named), layoutInfo.Size), nil
	}
	if decl.Interface != nil {
		return fmt.Sprintf("type :%s = { l, l }", qbeTypeName(state, decl.Named)), nil
	}
	return "", nil
}

func emitGlobals(b *strings.Builder, state *moduleState, globals []*mir.Global) error {
	wrote := 0
	for _, g := range globals {
		if g == nil {
			continue
		}
		line, err := lowerGlobal(state, g)
		if err != nil {
			return err
		}
		if line == "" {
			continue
		}
		if wrote > 0 {
			b.WriteByte('\n')
		}
		b.WriteString(line)
		b.WriteByte('\n')
		wrote++
	}
	return nil
}

func lowerGlobal(state *moduleState, g *mir.Global) (string, error) {
	if g.Init == nil {
		return "", nil
	}
	name := qbeSymbol(state, []string{g.Name})
	if isInterfaceAggregate(g.Type) {
		if init, ok := g.Init.(*mir.InterfaceValue); ok {
			return lowerGlobalInterface(state, name, g.Type, init)
		}
		return "", fmt.Errorf("global %s: interface initializer must be an interface coercion", g.Name)
	}
	if isUnionAggregate(g.Type) {
		body, err := lowerGlobalUnion(state, g.Type, g.Init)
		if err != nil {
			return "", fmt.Errorf("global %s: %w", g.Name, err)
		}
		return fmt.Sprintf("data $%s = { %s }", name, body), nil
	}
	switch v := g.Init.(type) {
	case *mir.CompositeValue:
		body, err := lowerGlobalComposite(state, g.Type, v)
		if err != nil {
			return "", fmt.Errorf("global %s: %w", g.Name, err)
		}
		return fmt.Sprintf("data $%s = { %s }", name, body), nil
	case *mir.NumberValue:
		tok, lit, err := qbeDataLiteral(g.Type, v.Value)
		if err != nil {
			return "", fmt.Errorf("global %s: %w", g.Name, err)
		}
		return fmt.Sprintf("data $%s = { %s %s }", name, tok, lit), nil
	case *mir.BoolValue:
		lit := "0"
		if v.Value {
			lit = "1"
		}
		return fmt.Sprintf("data $%s = { b %s }", name, lit), nil
	case *mir.StringValue:
		return fmt.Sprintf("data $%s = { b %q, b 0 }", name, v.Value), nil
	default:
		return "", fmt.Errorf("global %s: unsupported initializer %T", g.Name, g.Init)
	}
}

func isInterfaceAggregate(typ typeinfo.Type) bool {
	switch t := typ.(type) {
	case *typeinfo.NamedType:
		return namedIsInterface(t)
	case *typeinfo.InterfaceType:
		return true
	default:
		return false
	}
}

func lowerGlobalInterface(state *moduleState, name string, target typeinfo.Type, init *mir.InterfaceValue) (string, error) {
	if state == nil || init == nil {
		return "", fmt.Errorf("invalid interface global initializer")
	}
	dataSym, body, err := lowerInterfaceGlobalData(state, name, init)
	if err != nil {
		return "", err
	}
	vtSym, err := ensureQBEInterfaceVTable(state, target, init)
	if err != nil {
		return "", err
	}
	lines := []string{}
	if body != "" {
		lines = append(lines, body)
	}
	lines = append(lines, fmt.Sprintf("data $%s = { l $%s, l $%s }", name, dataSym, vtSym))
	return strings.Join(lines, "\n"), nil
}

func lowerInterfaceGlobalData(state *moduleState, ownerName string, init *mir.InterfaceValue) (string, string, error) {
	sym := sanitizeIdent(ownerName + "__iface_data")
	switch v := init.Value.(type) {
	case *mir.NameValue:
		if v.LinkName != "" {
			return sanitizeIdent(v.LinkName), "", nil
		}
		return qbeSymbol(state, v.Path), "", nil
	case *mir.NumberValue:
		tok, lit, err := qbeDataLiteral(init.ConcreteType, v.Value)
		if err != nil {
			return "", "", err
		}
		return sym, fmt.Sprintf("data $%s = { %s %s }", sym, tok, lit), nil
	case *mir.BoolValue:
		lit := "0"
		if v.Value {
			lit = "1"
		}
		return sym, fmt.Sprintf("data $%s = { b %s }", sym, lit), nil
	case *mir.StringValue:
		return sym, fmt.Sprintf("data $%s = { b %q, b 0 }", sym, v.Value), nil
	case *mir.CompositeValue:
		body, err := lowerGlobalComposite(state, init.ConcreteType, v)
		if err != nil {
			return "", "", err
		}
		ty, err := qbeABIType(state, init.ConcreteType)
		if err != nil {
			return "", "", err
		}
		return sym, fmt.Sprintf("data $%s = { %s }", sym, bodyForTypedQBEGlobal(strings.TrimPrefix(ty, ":"), body)), nil
	default:
		return "", "", fmt.Errorf("unsupported interface global initializer payload %T", init.Value)
	}
}

func bodyForTypedQBEGlobal(typeName, body string) string {
	if typeName == "" {
		return body
	}
	if strings.HasPrefix(body, typeName+" ") || strings.HasPrefix(body, "{") {
		return body
	}
	return body
}

func lowerGlobalUnion(state *moduleState, typ typeinfo.Type, init mir.Value) (string, error) {
	info, err := unionLayoutInfo(state, typ)
	if err != nil {
		return "", err
	}
	size := info.Size
	tok, lit, err := qbeDataItem(state, init.Type(), init)
	if err != nil {
		return "", err
	}
	itemSize, _, err := qbeScalarSizeAlign(init.Type())
	if err != nil {
		return "", fmt.Errorf("unsupported union global initializer type %s", typeinfo.FormatType(typeStringer{init.Type()}))
	}
	memberIndex, err := unionMemberIndex(info.Members, init.Type())
	if err != nil {
		return "", err
	}
	parts := []string{"w " + fmt.Sprintf("%d", memberIndex)}
	if info.PayloadOffset > 4 {
		parts = append(parts, fmt.Sprintf("z %d", info.PayloadOffset-4))
	}
	parts = append(parts, fmt.Sprintf("%s %s", tok, lit))
	if size > info.PayloadOffset+itemSize {
		parts = append(parts, fmt.Sprintf("z %d", size-(info.PayloadOffset+itemSize)))
	}
	return strings.Join(parts, ", "), nil
}

func emitFunction(b *strings.Builder, state *moduleState, fn *mir.Function) error {
	if err := prepareFunctionState(state, fn); err != nil {
		return err
	}
	ret, err := qbeABIType(state, fn.Result)
	if err != nil {
		return fmt.Errorf("function %s result: %w", fn.Name, err)
	}
	name := fn.LinkName
	if name == "" {
		name = qbeSymbol(state, []string{fn.Name})
	} else {
		name = sanitizeIdent(name)
	}
	// Export the entry point so the C runtime linker can find $main.
	if name == "main" {
		fmt.Fprintf(b, "export ")
	}
	fmt.Fprintf(b, "function")
	if ret != "" {
		fmt.Fprintf(b, " %s", ret)
	}
	paramParts := make([]string, 0, len(fn.Params))
	for _, param := range fn.Params {
		if param == nil {
			continue
		}
		if isAggregateType(state, param.Type) {
			paramParts = append(paramParts, fmt.Sprintf("l %s", qbeLocalName(param.Name)))
			continue
		}
		pty, err := qbeABIType(state, param.Type)
		if err != nil {
			return fmt.Errorf("function %s param %s: %w", fn.Name, param.Name, err)
		}
		paramParts = append(paramParts, fmt.Sprintf("%s %s", pty, qbeLocalName(param.Name)))
	}
	fmt.Fprintf(b, " $%s(%s) {\n", name, strings.Join(paramParts, ", "))
	blocks := append([]*mir.Block(nil), fn.Blocks...)
	sort.Slice(blocks, func(i, j int) bool { return blocks[i].ID < blocks[j].ID })
	for _, block := range blocks {
		if block == nil {
			continue
		}
		fmt.Fprintf(b, "%s\n", qbeBlockLabel(fn, block.ID))
		if block.ID == fn.EntryID {
			for _, line := range entryPrelude(state) {
				fmt.Fprintf(b, "\t%s\n", line)
			}
		}
		for _, instr := range block.Instructions {
			state.pendingLines = nil
			line, err := lowerInstr(state, instr)
			if err != nil {
				return fmt.Errorf("function %s block %d: %w", fn.Name, block.ID, err)
			}
			for _, pl := range state.pendingLines {
				fmt.Fprintf(b, "\t%s\n", pl)
			}
			if line == "" {
				continue
			}
			fmt.Fprintf(b, "\t%s\n", line)
		}
		state.pendingLines = nil
		term, err := lowerTerm(state, block.Terminator)
		if err != nil {
			return fmt.Errorf("function %s block %d: %w", fn.Name, block.ID, err)
		}
		for _, pl := range state.pendingLines {
			fmt.Fprintf(b, "\t%s\n", pl)
		}
		fmt.Fprintf(b, "\t%s\n", term)
	}
	b.WriteString("}\n")
	return nil
}

func lowerInstr(state *moduleState, instr mir.Instr) (string, error) {
	switch i := instr.(type) {
	case nil:
		return "", nil
	case *mir.BindInstr:
		return lowerAssignLike(state, i.Name, i.Type, i.Value)
	case *mir.AssignInstr:
		if local := findLocalByID(state.fn, i.TargetID); local != nil && local.IsTemp {
			if field, ok := i.Value.(*mir.FieldValue); ok && isInterfaceAggregate(field.Base.Type()) {
				state.tempValues[i.TargetID] = field
				return "", nil
			}
		}
		name := localNameByID(state.fn, i.TargetID)
		return lowerAssignLike(state, name, localTypeByID(state.fn, i.TargetID), i.Value)
	case *mir.ComputeInstr:
		if local := findLocalByID(state.fn, i.TargetID); local != nil && local.IsTemp {
			if field, ok := i.Value.(*mir.FieldValue); ok && isInterfaceAggregate(field.Base.Type()) {
				state.tempValues[i.TargetID] = field
				return "", nil
			}
		}
		name := localNameByID(state.fn, i.TargetID)
		return lowerAssignLike(state, name, i.Type, i.Value)
	case *mir.StoreFieldInstr:
		return lowerStoreField(state, i)
	case *mir.StoreInstr:
		return lowerStorePlace(state, i)
	case *mir.EvalInstr:
		if call, ok := i.Value.(*mir.CallValue); ok {
			return lowerCall(state, "", nil, call)
		}
		return "", nil
	case *mir.DeferInstr:
		// Defers are only bookkeeping at the registration site. Cleanup blocks
		// already contain the lowered deferred body, so nothing is emitted here.
		return "", nil
	case *mir.UnsafeInstr:
		// Unsafe marker: safety is enforced at type-check time; no code to emit.
		return "", nil
	default:
		return "", fmt.Errorf("unsupported MIR instruction %T", instr)
	}
}

func lowerAssignLike(state *moduleState, name string, typ typeinfo.Type, value mir.Value) (string, error) {
	if local := findLocalByName(state.fn, name); local != nil {
		if agg, ok := state.aggLocals[local.ID]; ok {
			return lowerAggregateAssign(state, agg, value)
		}
		if sc, ok := state.scalarLocals[local.ID]; ok {
			return lowerScalarAllocaAssign(state, sc, value)
		}
	}
	return lowerSSAAssign(state, name, typ, value)
}

func lowerScalarAllocaAssign(state *moduleState, sc *scalarAllocaLocal, value mir.Value) (string, error) {
	tmpName := strings.TrimPrefix(freshTemp(state, "asgn"), "%")
	line, err := lowerSSAAssign(state, tmpName, sc.Type, value)
	if err != nil {
		return "", err
	}
	resultName := qbeLocalName(tmpName)
	if line != "" {
		parts := strings.Split(strings.TrimRight(line, "\n"), "\n")
		for i := len(parts) - 1; i >= 0; i-- {
			p := strings.TrimSpace(parts[i])
			if strings.HasPrefix(p, "%") {
				if idx := strings.Index(p, " ="); idx > 0 {
					resultName = strings.TrimSpace(p[:idx])
					break
				}
			}
		}
	}
	storeOp, err := qbeStoreOp(sc.Type)
	if err != nil {
		return "", err
	}
	storeLine := fmt.Sprintf("%s %s, %s", storeOp, resultName, qbeLocalName(sc.PtrName))
	if line == "" {
		return storeLine, nil
	}
	return line + "\n\t" + storeLine, nil
}

func lowerSSAAssign(state *moduleState, name string, typ typeinfo.Type, value mir.Value) (string, error) {
	if call, ok := value.(*mir.CallValue); ok {
		return lowerCall(state, name, typ, call)
	}
	if field, ok := value.(*mir.FieldLoadValue); ok {
		return lowerFieldLoad(state, name, typ, field)
	}
	if field, ok := value.(*mir.FieldValue); ok {
		return lowerResolvedFieldValueLoad(state, name, typ, field)
	}
	if idx, ok := value.(*mir.IndexValue); ok {
		return lowerIndexLoad(state, name, typ, idx)
	}
	if load, ok := value.(*mir.LoadValue); ok {
		return lowerLoadValue(state, name, typ, load)
	}
	if bin, ok := value.(*mir.BinaryValue); ok {
		if line, handled, err := lowerAggregateCompare(state, name, typ, bin); handled || err != nil {
			return line, err
		}
	}
	qtype, err := qbeBaseType(typ)
	if err != nil {
		return "", err
	}
	expr, err := lowerValue(state, value)
	if err != nil {
		return "", err
	}
	// QBE assignment RHS must be an instruction, not a bare value.
	// Raw values (constants, registers, globals) require the 'copy' opcode.
	if qbeValueNeedsCopy(value) {
		return fmt.Sprintf("%s =%s copy %s", qbeLocalName(name), qtype, expr), nil
	}
	return fmt.Sprintf("%s =%s %s", qbeLocalName(name), qtype, expr), nil
}

func lowerAggregateCompare(state *moduleState, targetName string, targetType typeinfo.Type, bin *mir.BinaryValue) (string, bool, error) {
	if bin == nil || (bin.Op != "==" && bin.Op != "!=") {
		return "", false, nil
	}
	if !isAggregateType(state, bin.Left.Type()) || !isAggregateType(state, bin.Right.Type()) {
		return "", false, nil
	}
	if _, err := qbeBaseType(targetType); err != nil {
		return "", true, err
	}
	leftStruct, err := lookupStructLayout(state, bin.Left.Type())
	if err != nil {
		return "", true, err
	}
	rightStruct, err := lookupStructLayout(state, bin.Right.Type())
	if err != nil {
		return "", true, err
	}
	if len(leftStruct.Fields) != len(rightStruct.Fields) {
		return "", true, fmt.Errorf("aggregate comparison requires matching layouts")
	}
	lines := make([]string, 0, len(leftStruct.Fields)*4+2)
	prevCmp := ""
	for i, field := range leftStruct.Fields {
		if field == nil {
			continue
		}
		if isAggregateType(state, field.Type) {
			return "", true, fmt.Errorf("nested aggregate comparison is not supported yet")
		}
		leftLines, leftAddr, _, err := lowerFieldAddress(state, bin.Left, i)
		if err != nil {
			return "", true, err
		}
		rightLines, rightAddr, _, err := lowerFieldAddress(state, bin.Right, i)
		if err != nil {
			return "", true, err
		}
		lines = append(lines, leftLines...)
		lines = append(lines, rightLines...)
		loadOp, resultType, err := qbeLoadOp(field.Type)
		if err != nil {
			return "", true, err
		}
		leftTmp := freshTemp(state, "cmp")
		rightTmp := freshTemp(state, "cmp")
		lines = append(lines, fmt.Sprintf("%s =%s %s %s", leftTmp, resultType, loadOp, leftAddr))
		lines = append(lines, fmt.Sprintf("%s =%s %s %s", rightTmp, resultType, loadOp, rightAddr))
		cmpOp, err := qbeCompareOp("==", field.Type)
		if err != nil {
			return "", true, err
		}
		cmpTmp := freshTemp(state, "cmp")
		lines = append(lines, fmt.Sprintf("%s =w %s %s, %s", cmpTmp, cmpOp, leftTmp, rightTmp))
		if prevCmp == "" {
			prevCmp = cmpTmp
			continue
		}
		merged := freshTemp(state, "cmp")
		lines = append(lines, fmt.Sprintf("%s =w and %s, %s", merged, prevCmp, cmpTmp))
		prevCmp = merged
	}
	if prevCmp == "" {
		prevCmp = "1"
	}
	if bin.Op == "!=" {
		inv := freshTemp(state, "cmp")
		lines = append(lines, fmt.Sprintf("%s =w xor %s, 1", inv, prevCmp))
		prevCmp = inv
	}
	lines = append(lines, fmt.Sprintf("%s =w copy %s", qbeLocalName(targetName), prevCmp))
	return strings.Join(lines, "\n\t"), true, nil
}

func lowerLoadValue(state *moduleState, targetName string, targetType typeinfo.Type, load *mir.LoadValue) (string, error) {
	ptr, err := lowerValue(state, load.Pointer)
	if err != nil {
		return "", err
	}
	op, resultType, err := qbeLoadOp(targetType)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("%s =%s %s %s", qbeLocalName(targetName), resultType, op, ptr), nil
}

func lowerCall(state *moduleState, targetName string, targetType typeinfo.Type, call *mir.CallValue) (string, error) {
	if local, ok := call.Callee.(*mir.LocalValue); ok {
		if field, ok := state.tempValues[local.LocalID].(*mir.FieldValue); ok && len(call.Args) > 0 && isInterfaceAggregate(call.Args[0].Type()) {
			return lowerInterfaceCall(state, targetName, targetType, call, field)
		}
	}
	if field, ok := call.Callee.(*mir.FieldValue); ok && len(call.Args) > 0 && isInterfaceAggregate(call.Args[0].Type()) {
		return lowerInterfaceCall(state, targetName, targetType, call, field)
	}
	callee, err := lowerCallee(state, call.Callee)
	if err != nil {
		return "", err
	}
	if call.IsConstructor {
		if targetName != "" {
			if local := findLocalByName(state.fn, targetName); local != nil {
				if agg, ok := state.aggLocals[local.ID]; ok {
					return lowerConstructorCall(state, qbeLocalName(agg.PtrName), call, callee)
				}
			}
		}
		return lowerConstructorCallDiscard(state, targetType, call, callee)
	}
	if isBuiltinPrintCall(call) {
		return lowerBuiltinPrintCall(state, call)
	}
	args := make([]string, 0, len(call.Args))
	for _, arg := range call.Args {
		if isAggregateType(state, arg.Type()) {
			prefix, ptr, err := lowerAggregateValuePointer(state, arg)
			if err != nil {
				return "", err
			}
			if len(prefix) != 0 {
				state.pendingLines = append(state.pendingLines, prefix...)
			}
			args = append(args, fmt.Sprintf("l %s", ptr))
			continue
		}
		atype, err := qbeABIType(state, arg.Type())
		if err != nil {
			return "", err
		}
		aval, err := lowerValue(state, arg)
		if err != nil {
			return "", err
		}
		args = append(args, fmt.Sprintf("%s %s", atype, aval))
	}
	callText := fmt.Sprintf("call %s(%s)", callee, strings.Join(args, ", "))
	if targetName == "" {
		return callText, nil
	}
	qtype, err := qbeBaseType(targetType)
	if err != nil {
		return "", err
	}
	if qtype == "" {
		// void return: no assignment
		return callText, nil
	}
	return fmt.Sprintf("%s =%s %s", qbeLocalName(targetName), qtype, callText), nil
}

func isBuiltinPrintCall(call *mir.CallValue) bool {
	if call == nil {
		return false
	}
	callee, ok := call.Callee.(*mir.NameValue)
	if !ok || callee == nil {
		return false
	}
	if callee.LinkName == "global__print" {
		return true
	}
	return len(callee.Path) == 2 && callee.Path[0] == "global" && callee.Path[1] == "print"
}

func lowerBuiltinPrintCall(state *moduleState, call *mir.CallValue) (string, error) {
	if call == nil || len(call.Args) != 1 {
		return "", fmt.Errorf("builtin print expects exactly one argument")
	}
	arg := call.Args[0]
	if arg == nil {
		return "", fmt.Errorf("builtin print argument is nil")
	}
	if _, ok := arg.Type().(*typeinfo.StringType); ok {
		prefix, ptr, err := lowerAggregateValuePointer(state, arg)
		if err != nil {
			return "", err
		}
		return joinQBELines(prefix, []string{fmt.Sprintf("call $global__print_str(l %s)", ptr)}), nil
	}
	if builtin, ok := arg.Type().(*typeinfo.BuiltinType); ok {
		return lowerBuiltinPrintPrimitive(state, arg, builtin.Name)
	}
	if qbeIsPointerLike(arg.Type()) {
		val, err := lowerValue(state, arg)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("call $global__print_ptr(l %s)", val), nil
	}
	sym := emitQBEStringConstant(state, arg.Type().String())
	return fmt.Sprintf("call $global__print_type(l $%s)", sym), nil
}

func qbePointerInner(t typeinfo.Type) (typeinfo.Type, bool) {
	switch pt := unwrapNamed(t).(type) {
	case *typeinfo.PointerType:
		return pt.Inner, true
	case *typeinfo.RefType:
		return pt.Inner, true
	case *typeinfo.RawPtrType:
		return pt.Inner, true
	default:
		return nil, false
	}
}

func qbeIsPointerLike(t typeinfo.Type) bool {
	_, ok := qbePointerInner(t)
	return ok
}

func lowerBuiltinPrintPrimitive(state *moduleState, arg mir.Value, name string) (string, error) {
	val, err := lowerValue(state, arg)
	if err != nil {
		return "", err
	}
	switch name {
	case "bool":
		return fmt.Sprintf("call $global__print_bool(w %s)", val), nil
	case "i8", "i16", "i32", "i64", "isize":
		return lowerBuiltinPrintIntCast(state, val, name, "i64", "$global__print_i64")
	case "u8", "u16", "u32", "u64", "usize":
		return lowerBuiltinPrintIntCast(state, val, name, "u64", "$global__print_u64")
	case "f32", "f64":
		return lowerBuiltinPrintFloatCast(state, val, name)
	case "char":
		return fmt.Sprintf("call $global__print_char(w %s)", val), nil
	default:
		sym := emitQBEStringConstant(state, arg.Type().String())
		return fmt.Sprintf("call $global__print_type(l $%s)", sym), nil
	}
}

func lowerBuiltinPrintIntCast(state *moduleState, value, srcName, dstName, callee string) (string, error) {
	dstType := "l"
	if srcName == dstName {
		return fmt.Sprintf("call %s(%s %s)", callee, dstType, value), nil
	}
	op, ok := qbeIntCastOp(srcName, dstName)
	if !ok {
		return "", fmt.Errorf("unsupported print integer cast from %s to %s", srcName, dstName)
	}
	tmp := freshTemp(state, "print")
	return joinQBELines([]string{
		fmt.Sprintf("%s =l %s %s", tmp, op, value),
		fmt.Sprintf("call %s(l %s)", callee, tmp),
	}), nil
}

func lowerBuiltinPrintFloatCast(state *moduleState, value, srcName string) (string, error) {
	if srcName == "f64" {
		return fmt.Sprintf("call $global__print_f64(d %s)", value), nil
	}
	op, ok := qbeFloatCastOp(srcName, "f64")
	if !ok {
		return "", fmt.Errorf("unsupported print float cast from %s to f64", srcName)
	}
	tmp := freshTemp(state, "print")
	return joinQBELines([]string{
		fmt.Sprintf("%s =d %s %s", tmp, op, value),
		fmt.Sprintf("call $global__print_f64(d %s)", tmp),
	}), nil
}

func lowerAggregateValuePointer(state *moduleState, value mir.Value) ([]string, string, error) {
	if value == nil {
		return nil, "", fmt.Errorf("nil aggregate value")
	}
	switch v := value.(type) {
	case *mir.LocalValue:
		if agg, ok := state.aggLocals[v.LocalID]; ok {
			return nil, qbeLocalName(agg.PtrName), nil
		}
	case *mir.NameValue:
		if v.LinkName != "" {
			return nil, "$" + sanitizeIdent(v.LinkName), nil
		}
		return nil, "$" + qbeSymbol(state, v.Path), nil
	}
	if !isAggregateType(state, value.Type()) {
		return nil, "", fmt.Errorf("value %T is not aggregate", value)
	}
	size, align, err := aggregateSizeAlign(state, value.Type())
	if err != nil {
		return nil, "", err
	}
	tmp := freshTemp(state, "print_agg")
	agg := &aggregateLocal{PtrName: strings.TrimPrefix(tmp, "%"), Type: value.Type(), Size: size, Align: align}
	assign, err := lowerAggregateAssign(state, agg, value)
	if err != nil {
		return nil, "", err
	}
	lines := []string{fmt.Sprintf("%s =l alloc%d %d", tmp, normalizeQBEAlign(align), size)}
	if assign != "" {
		lines = append(lines, strings.Split(assign, "\n\t")...)
	}
	return lines, tmp, nil
}

func joinQBELines(lines ...[]string) string {
	flat := make([]string, 0)
	for _, group := range lines {
		for _, line := range group {
			if strings.TrimSpace(line) == "" {
				continue
			}
			flat = append(flat, line)
		}
	}
	return strings.Join(flat, "\n\t")
}

func lowerConstructorCall(state *moduleState, dstPtr string, call *mir.CallValue, callee string) (string, error) {
	args := make([]string, 0, len(call.Args)+1)
	args = append(args, fmt.Sprintf("l %s", dstPtr))
	for _, arg := range call.Args {
		if isAggregateType(state, arg.Type()) {
			prefix, ptr, err := lowerAggregateValuePointer(state, arg)
			if err != nil {
				return "", err
			}
			if len(prefix) != 0 {
				state.pendingLines = append(state.pendingLines, prefix...)
			}
			args = append(args, fmt.Sprintf("l %s", ptr))
			continue
		}
		atype, err := qbeABIType(state, arg.Type())
		if err != nil {
			return "", err
		}
		aval, err := lowerValue(state, arg)
		if err != nil {
			return "", err
		}
		args = append(args, fmt.Sprintf("%s %s", atype, aval))
	}
	return fmt.Sprintf("call %s(%s)", callee, strings.Join(args, ", ")), nil
}

func lowerImplicitConstructorCall(state *moduleState, dstPtr string, path []string) (string, error) {
	if len(path) == 0 {
		return "", nil
	}
	return fmt.Sprintf("call $%s(l %s)", qbeSymbol(state, path), dstPtr), nil
}

func lowerConstructorCallDiscard(state *moduleState, targetType typeinfo.Type, call *mir.CallValue, callee string) (string, error) {
	if targetType == nil || !isAggregateType(state, targetType) {
		return "", fmt.Errorf("constructor call requires aggregate target")
	}
	size, align, err := aggregateSizeAlign(state, targetType)
	if err != nil {
		return "", err
	}
	tmp := freshTemp(state, "ctor_tmp")
	callText, err := lowerConstructorCall(state, tmp, call, callee)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("%s =l alloc%d %d\n\t%s", tmp, normalizeQBEAlign(align), size, callText), nil
}

// lowerPanicTerm emits a call to ferret__panic(l ptr) followed by hlt.
// String literals are null-terminated *i8 constants; we pass the pointer directly.
func lowerPanicTerm(state *moduleState, t *mir.PanicTerm) (string, error) {
	switch v := t.Value.(type) {
	case *mir.StringValue:
		sym := emitQBEStringConstant(state, v.Value)
		return fmt.Sprintf("call $ferret__panic(l $%s)\n\thlt", sym), nil
	default:
		if _, ok := unwrapNamed(t.Value.Type()).(*typeinfo.StringType); ok {
			addr, err := lowerAddrOf(state, &mir.AddrOfValue{Source: t.Value})
			if err != nil {
				if lv, valueErr := lowerValue(state, t.Value); valueErr == nil {
					addr = lv
				} else {
					return "", fmt.Errorf("panic: unsupported string payload (%T): %w", t.Value, err)
				}
			}
			return fmt.Sprintf("call $global__panic(l %s)\n\thlt", addr), nil
		}
		return "", fmt.Errorf("panic: unsupported payload type %T", t.Value)
	}
}

func lowerTerm(state *moduleState, term mir.Terminator) (string, error) {
	switch t := term.(type) {
	case nil:
		return "hlt", nil
	case *mir.ExitTerm:
		return "ret", nil
	case *mir.JumpTerm:
		return fmt.Sprintf("jmp %s", qbeBlockLabel(state.fn, t.TargetID)), nil
	case *mir.BranchTerm:
		cond, err := lowerValue(state, t.Cond)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("jnz %s, %s, %s", cond, qbeBlockLabel(state.fn, t.TrueID), qbeBlockLabel(state.fn, t.FalseID)), nil
	case *mir.ReturnTerm:
		if t.CleanupID >= 0 {
			return fmt.Sprintf("jmp %s", qbeBlockLabel(state.fn, t.CleanupID)), nil
		}
		if t.Value == nil {
			return "ret", nil
		}
		if alias, ok := resolveQBETempValue(state, t.Value); ok {
			t.Value = alias
		}
		if call, ok := t.Value.(*mir.CallValue); ok && call.IsConstructor {
			size, align, err := aggregateSizeAlign(state, call.Type())
			if err != nil {
				return "", err
			}
			callee, err := lowerCallee(state, call.Callee)
			if err != nil {
				return "", err
			}
			tmpPtr := freshTemp(state, "ctor_ret")
			callText, err := lowerConstructorCall(state, tmpPtr, call, callee)
			if err != nil {
				return "", err
			}
			return fmt.Sprintf("%s =l alloc%d %d\n\t%s\n\tret %s", tmpPtr, normalizeQBEAlign(align), size, callText, tmpPtr), nil
		}
		if isAggregateType(state, t.Value.Type()) {
			switch v := t.Value.(type) {
			case *mir.CallValue, *mir.CastValue:
				val, err := lowerValue(state, v)
				if err != nil {
					return "", err
				}
				return fmt.Sprintf("ret %s", val), nil
			}
			prefix, ptr, err := lowerAggregateValuePointer(state, t.Value)
			if err != nil {
				return "", err
			}
			lines := make([]string, 0, len(prefix)+1)
			lines = append(lines, prefix...)
			lines = append(lines, fmt.Sprintf("ret %s", ptr))
			return strings.Join(lines, "\n\t"), nil
		}
		val, err := lowerValue(state, t.Value)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("ret %s", val), nil
	case *mir.PanicTerm:
		if t.CleanupID >= 0 {
			return fmt.Sprintf("jmp %s", qbeBlockLabel(state.fn, t.CleanupID)), nil
		}
		return lowerPanicTerm(state, t)
	case *mir.SwitchTerm:
		return lowerSwitchTerm(state, t)
	default:
		return "", fmt.Errorf("unsupported MIR terminator %T", term)
	}
}

func lowerSwitchTerm(state *moduleState, t *mir.SwitchTerm) (string, error) {
	if t == nil {
		return "", fmt.Errorf("invalid switch terminator")
	}
	if len(t.Cases) == 0 {
		return fmt.Sprintf("jmp %s", qbeBlockLabel(state.fn, t.DefaultID)), nil
	}
	value, err := lowerValue(state, t.Value)
	if err != nil {
		return "", err
	}
	cmpOp, err := qbeCompareOp("==", t.Value.Type())
	if err != nil {
		return "", err
	}
	lines := make([]string, 0, len(t.Cases)*3+1)
	for i, sc := range t.Cases {
		caseVal, err := lowerValue(state, sc.Expr)
		if err != nil {
			return "", err
		}
		cmp := freshTemp(state, "switch")
		next := qbeFreshLabel(state, "sw")
		falseLabel := next
		if i == len(t.Cases)-1 {
			falseLabel = qbeBlockLabel(state.fn, t.DefaultID)
		}
		lines = append(lines,
			fmt.Sprintf("%s =w %s %s, %s", cmp, cmpOp, value, caseVal),
			fmt.Sprintf("jnz %s, %s, %s", cmp, qbeBlockLabel(state.fn, sc.TargetID), falseLabel),
		)
		if i != len(t.Cases)-1 {
			lines = append(lines, next)
		}
	}
	return strings.Join(lines, "\n\t"), nil
}

func lowerFieldLoad(state *moduleState, targetName string, targetType typeinfo.Type, field *mir.FieldLoadValue) (string, error) {
	lines, addr, _, err := lowerFieldAddress(state, field.Base, field.FieldIndex)
	if err != nil {
		return "", err
	}
	op, resultType, err := qbeLoadOp(targetType)
	if err != nil {
		return "", err
	}
	lines = append(lines, fmt.Sprintf("%s =%s %s %s", qbeLocalName(targetName), resultType, op, addr))
	return strings.Join(lines, "\n\t"), nil
}

func lowerFieldValueLoad(state *moduleState, targetName string, targetType typeinfo.Type, base mir.Value, fieldIndex int) (string, error) {
	lines, addr, _, err := lowerFieldAddress(state, base, fieldIndex)
	if err != nil {
		return "", err
	}
	op, resultType, err := qbeLoadOp(targetType)
	if err != nil {
		return "", err
	}
	lines = append(lines, fmt.Sprintf("%s =%s %s %s", qbeLocalName(targetName), resultType, op, addr))
	return strings.Join(lines, "\n\t"), nil
}

func lowerResolvedFieldValueLoad(state *moduleState, targetName string, targetType typeinfo.Type, field *mir.FieldValue) (string, error) {
	if field == nil {
		return "", fmt.Errorf("nil field value")
	}
	fieldIndex, err := qbeResolveFieldIndex(state, qbeFieldBaseType(state, field.Base), field.FieldIndex, field.MemberName)
	if err != nil {
		return "", err
	}
	return lowerFieldValueLoad(state, targetName, targetType, field.Base, fieldIndex)
}

func qbeResolveFieldIndex(state *moduleState, baseType typeinfo.Type, fieldIndex int, memberName string) (int, error) {
	if fieldIndex >= 0 {
		return fieldIndex, nil
	}
	structLayout, err := lookupStructLayout(state, baseType)
	if err != nil {
		return -1, err
	}
	for _, field := range structLayout.Fields {
		if field != nil && field.Name == memberName {
			return field.SemanticIndex, nil
		}
	}
	return -1, fmt.Errorf("unknown field %q", memberName)
}

// lowerIndexLoad lowers arr[index] as an rvalue via QBE load.
func lowerIndexLoad(state *moduleState, targetName string, targetType typeinfo.Type, idx *mir.IndexValue) (string, error) {
	if _, ok := unwrapNamed(idx.Base.Type()).(*typeinfo.SliceType); ok {
		return lowerSliceIndexLoad(state, targetName, targetType, idx)
	}
	lines, addr, err := lowerQBEIndexAddress(state, idx.Base, idx.Index, idx.Base.Type())
	if err != nil {
		return "", err
	}
	op, resultType, err := qbeLoadOp(targetType)
	if err != nil {
		return "", err
	}
	lines = append(lines, fmt.Sprintf("%s =%s %s %s", qbeLocalName(targetName), resultType, op, addr))
	return strings.Join(lines, "\n\t"), nil
}

func lowerSliceIndexLoad(state *moduleState, targetName string, targetType typeinfo.Type, idx *mir.IndexValue) (string, error) {
	baseExpr, err := lowerValue(state, idx.Base)
	if err != nil {
		return "", err
	}
	indexExpr, err := lowerValue(state, idx.Index)
	if err != nil {
		return "", err
	}
	elemType := targetType
	elemSize, _, err := qbeScalarSizeAlign(elemType)
	if err != nil {
		elemSize, _, err = aggregateSizeAlign(state, elemType)
		if err != nil {
			return "", fmt.Errorf("cannot compute size of indexed element type %s", elemType)
		}
	}
	op, resultType, err := qbeLoadOp(targetType)
	if err != nil {
		return "", err
	}
	lines := make([]string, 0, 5)
	dataPtr := freshTemp(state, "slice_data")
	lines = append(lines, fmt.Sprintf("%s =l loadl %s", dataPtr, baseExpr))
	scaled := indexExpr
	if elemSize != 1 {
		scaledTmp := freshTemp(state, "idx")
		lines = append(lines, fmt.Sprintf("%s =l mul %s, %d", scaledTmp, indexExpr, elemSize))
		scaled = scaledTmp
	}
	elemPtr := freshTemp(state, "elem")
	lines = append(lines, fmt.Sprintf("%s =l add %s, %s", elemPtr, dataPtr, scaled))
	lines = append(lines, fmt.Sprintf("%s =%s %s %s", qbeLocalName(targetName), resultType, op, elemPtr))
	return strings.Join(lines, "\n\t"), nil
}

// lowerQBEIndexAddress computes ptr = base + index * elemSize.
func lowerQBEIndexAddress(state *moduleState, base mir.Value, index mir.Value, baseType typeinfo.Type) ([]string, string, error) {
	var elemType typeinfo.Type
	switch bt := baseType.(type) {
	case *typeinfo.ArrayType:
		elemType = bt.Inner
	default:
		var ok bool
		elemType, ok = qbePointerInner(baseType)
		if !ok {
			return nil, "", fmt.Errorf("cannot index into %T", baseType)
		}
	}
	elemSize, _, err := qbeScalarSizeAlign(elemType)
	if err != nil {
		// try aggregate size
		elemSize, _, err = aggregateSizeAlign(state, elemType)
		if err != nil {
			return nil, "", fmt.Errorf("cannot compute size of array element %s", elemType)
		}
	}
	baseExpr, err := lowerValue(state, base)
	if err != nil {
		return nil, "", err
	}
	indexExpr, err := lowerValue(state, index)
	if err != nil {
		return nil, "", err
	}
	var lines []string
	scaled := indexExpr
	if elemSize != 1 {
		scl := freshTemp(state, "idx")
		lines = append(lines, fmt.Sprintf("%s =l mul %s, %d", scl, indexExpr, elemSize))
		scaled = scl
	}
	addr := freshTemp(state, "elem")
	lines = append(lines, fmt.Sprintf("%s =l add %s, %s", addr, baseExpr, scaled))
	return lines, addr, nil
}

// lowerStorePlace lowers a StoreInstr (write to an lvalue place).
func lowerStorePlace(state *moduleState, instr *mir.StoreInstr) (string, error) {
	if instr == nil {
		return "", nil
	}
	if agg := unionAggregateLocalForPlace(state, instr.Target); agg != nil {
		return lowerUnionAssign(state, agg, instr.Value)
	}
	lines, addr, err := lowerQBEPlaceAddr(state, instr.Target)
	if err != nil {
		return "", err
	}
	val, err := lowerValue(state, instr.Value)
	if err != nil {
		return "", err
	}
	op, err := qbeStoreOp(instr.Value.Type())
	if err != nil {
		return "", err
	}
	if !qbeValueNeedsCopy(instr.Value) {
		qtype, err := qbeBaseType(instr.Value.Type())
		if err != nil {
			return "", err
		}
		tmp := freshTemp(state, "store")
		lines = append(lines, fmt.Sprintf("%s =%s %s", tmp, qtype, val))
		val = tmp
	}
	lines = append(lines, fmt.Sprintf("%s %s, %s", op, val, addr))
	return strings.Join(lines, "\n\t"), nil
}

func unionAggregateLocalForPlace(state *moduleState, place mir.Place) *aggregateLocal {
	switch p := place.(type) {
	case *mir.LocalPlace:
		if agg, ok := state.aggLocals[p.LocalID]; ok && isUnionAggregate(agg.Type) {
			return agg
		}
	case *mir.DerefPlace:
		if addr, ok := p.Pointer.(*mir.AddrOfValue); ok {
			switch src := addr.Source.(type) {
			case *mir.LocalValue:
				if agg, ok := state.aggLocals[src.LocalID]; ok && isUnionAggregate(agg.Type) {
					return agg
				}
			case *mir.NameValue:
				if len(src.Path) == 1 {
					if local := findLocalByName(state.fn, src.Path[0]); local != nil {
						if agg, ok := state.aggLocals[local.ID]; ok && isUnionAggregate(agg.Type) {
							return agg
						}
					}
				}
			}
		}
	}
	return nil
}

// lowerQBEPlaceAddr computes the QBE address for a place.
func lowerQBEPlaceAddr(state *moduleState, place mir.Place) ([]string, string, error) {
	switch p := place.(type) {
	case nil:
		return nil, "", fmt.Errorf("nil place")
	case *mir.LocalPlace:
		if agg, ok := state.aggLocals[p.LocalID]; ok {
			return nil, qbeLocalName(agg.PtrName), nil
		}
		if sc, ok := state.scalarLocals[p.LocalID]; ok {
			return nil, qbeLocalName(sc.PtrName), nil
		}
		return nil, qbeLocalName(localNameByID(state.fn, p.LocalID)), nil
	case *mir.FieldPlace:
		baseLines, basePtr, err := lowerQBEPlaceAddr(state, p.Base)
		if err != nil {
			return nil, "", err
		}
		baseType := qbePlaceType(state, p.Base)
		sl, err := lookupStructLayout(state, baseType)
		if err != nil {
			return nil, "", err
		}
		if p.FieldIndex < 0 || p.FieldIndex >= len(sl.Fields) {
			return nil, "", fmt.Errorf("invalid field index %d", p.FieldIndex)
		}
		field := sl.Fields[p.FieldIndex]
		if field.Offset == 0 {
			return baseLines, basePtr, nil
		}
		addrTmp := freshTemp(state, "addr")
		gepLine := fmt.Sprintf("%s =l add %s, %d", addrTmp, basePtr, field.Offset)
		return append(baseLines, gepLine), addrTmp, nil
	case *mir.IndexPlace:
		baseLines, basePtr, err := lowerQBEPlaceAddr(state, p.Base)
		if err != nil {
			return nil, "", err
		}
		baseType := qbePlaceType(state, p.Base)
		// Compute address using a fake LocalValue that returns basePtr
		var elemType typeinfo.Type
		if arr, ok := baseType.(*typeinfo.ArrayType); ok {
			elemType = arr.Inner
		} else if sl, ok := baseType.(*typeinfo.SliceType); ok {
			elemType = sl.Inner
			dataPtr := freshTemp(state, "slice_data")
			baseLines = append(baseLines, fmt.Sprintf("%s =l loadl %s", dataPtr, basePtr))
			basePtr = dataPtr
		} else {
			return nil, "", fmt.Errorf("IndexPlace base is not an array or slice: %T", baseType)
		}
		elemSize, _, err := qbeScalarSizeAlign(elemType)
		if err != nil {
			elemSize, _, err = aggregateSizeAlign(state, elemType)
			if err != nil {
				return nil, "", fmt.Errorf("cannot compute size of indexed element type %s", elemType)
			}
		}
		idxVal, err := lowerValue(state, p.Index)
		if err != nil {
			return nil, "", err
		}
		var idxLines []string
		scaled := idxVal
		if elemSize != 1 {
			scl := freshTemp(state, "idx")
			idxLines = append(idxLines, fmt.Sprintf("%s =l mul %s, %d", scl, idxVal, elemSize))
			scaled = scl
		}
		addrTmp := freshTemp(state, "elem")
		idxLines = append(idxLines, fmt.Sprintf("%s =l add %s, %s", addrTmp, basePtr, scaled))
		return append(baseLines, idxLines...), addrTmp, nil
	case *mir.DerefPlace:
		// *ptr: the address to write to is the pointer value itself.
		ptrVal, err := lowerValue(state, p.Pointer)
		if err != nil {
			return nil, "", err
		}
		return nil, ptrVal, nil
	default:
		return nil, "", fmt.Errorf("unsupported place %T for lowerQBEPlaceAddr", place)
	}
}

// qbePlaceType returns the type of variable at the root of a place.
func qbePlaceType(state *moduleState, place mir.Place) typeinfo.Type {
	if lp, ok := place.(*mir.LocalPlace); ok {
		if state.fn != nil && lp.LocalID >= 0 && lp.LocalID < len(state.fn.Locals) {
			return state.fn.Locals[lp.LocalID].Type
		}
	}
	return nil
}

// qbeScalarSizeAlign returns the size and alignment for scalar/pointer types.
func qbeScalarSizeAlign(typ typeinfo.Type) (int64, int64, error) {
	switch t := unwrapNamed(typ).(type) {
	case *typeinfo.BuiltinType:
		switch t.Name {
		case "bool", "u8", "i8":
			return 1, 1, nil
		case "u16", "i16":
			return 2, 2, nil
		case "u32", "i32", "char", "f32":
			return 4, 4, nil
		case "u64", "i64", "usize", "isize", "f64":
			return 8, 8, nil
		}
	case *typeinfo.PointerType, *typeinfo.RefType, *typeinfo.RawPtrType:
		return 8, 8, nil
	}
	return 0, 0, fmt.Errorf("not a scalar type: %s", typ)
}

// alignUpInt64 rounds size up to alignment.
func alignUpInt64(size, align int64) int64 {
	if align <= 1 {
		return size
	}
	return (size + align - 1) &^ (align - 1)
}

func lowerStoreField(state *moduleState, instr *mir.StoreFieldInstr) (string, error) {
	lines, addr, fieldType, err := lowerFieldAddress(state, instr.Base, instr.FieldIndex)
	if err != nil {
		return "", err
	}
	value, err := lowerValue(state, instr.Value)
	if err != nil {
		return "", err
	}
	op, err := qbeStoreOp(fieldType)
	if err != nil {
		return "", err
	}
	lines = append(lines, fmt.Sprintf("%s %s, %s", op, value, addr))
	return strings.Join(lines, "\n\t"), nil
}

func lowerFieldAddress(state *moduleState, base mir.Value, fieldIndex int) ([]string, string, typeinfo.Type, error) {
	structLayout, err := lookupStructLayout(state, base.Type())
	if err != nil {
		return nil, "", nil, err
	}
	if fieldIndex < 0 || fieldIndex >= len(structLayout.Fields) {
		return nil, "", nil, fmt.Errorf("invalid field index %d", fieldIndex)
	}
	field := structLayout.Fields[fieldIndex]
	baseVal, err := lowerValue(state, base)
	if err != nil {
		return nil, "", nil, err
	}
	if field.Offset == 0 {
		return nil, baseVal, field.Type, nil
	}
	addr := freshTemp(state, "addr")
	return []string{fmt.Sprintf("%s =l add %s, %d", addr, baseVal, field.Offset)}, addr, field.Type, nil
}

func lowerAggregateAssign(state *moduleState, agg *aggregateLocal, value mir.Value) (string, error) {
	if agg == nil {
		return "", fmt.Errorf("nil aggregate local")
	}
	if isInterfaceAggregate(agg.Type) {
		if iface, ok := value.(*mir.InterfaceValue); ok {
			return lowerInterfaceAssign(state, qbeLocalName(agg.PtrName), agg.Type, iface)
		}
		return "", fmt.Errorf("unsupported interface assignment %T", value)
	}
	if isUnionAggregate(agg.Type) {
		return lowerUnionAssign(state, agg, value)
	}
	switch v := value.(type) {
	case *mir.UnaryValue:
		if v.Op == "copy" || v.Op == "take" || v.Op == "comptime" {
			return lowerAggregateAssign(state, agg, v.Right)
		}
	case *mir.CastValue:
		expr, err := lowerCast(state, v)
		if err != nil {
			return "", err
		}
		abiType, err := qbeABIType(state, agg.Type)
		if err != nil {
			return "", err
		}
		temp := freshTemp(state, "aggcast")
		lines := []string{
			fmt.Sprintf("%s =%s %s", temp, abiType, expr),
		}
		if temp != qbeLocalName(agg.PtrName) {
			lines = append(lines, fmt.Sprintf("blit %s, %s, %d", temp, qbeLocalName(agg.PtrName), agg.Size))
		}
		return strings.Join(lines, "\n\t"), nil
	case *mir.CallValue:
		return lowerAggregateCall(state, agg, v)
	case *mir.LocalValue, *mir.NameValue, *mir.LoadValue, *mir.FieldLoadValue:
		src, err := lowerAggregateSource(state, value)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("blit %s, %s, %d", src, qbeLocalName(agg.PtrName), agg.Size), nil
	case *mir.CompositeValue:
		return lowerAggregateCompositeAssign(state, agg, v)
	}
	return "", fmt.Errorf("unsupported aggregate assignment %T", value)
}

func lowerInterfaceAssign(state *moduleState, dstPtr string, target typeinfo.Type, value *mir.InterfaceValue) (string, error) {
	lines, dataPtr, err := lowerInterfaceConcretePointer(state, value.Value, value.ConcreteType)
	if err != nil {
		return "", err
	}
	vtableSym, err := ensureQBEInterfaceVTable(state, target, value)
	if err != nil {
		return "", err
	}
	lines = append(lines, fmt.Sprintf("storel %s, %s", dataPtr, dstPtr))
	vtAddr := freshTemp(state, "iface_vt")
	lines = append(lines,
		fmt.Sprintf("%s =l add %s, 8", vtAddr, dstPtr),
		fmt.Sprintf("storel $%s, %s", vtableSym, vtAddr),
	)
	return strings.Join(lines, "\n\t"), nil
}

func lowerInterfaceConcretePointer(state *moduleState, value mir.Value, concreteType typeinfo.Type) ([]string, string, error) {
	switch v := value.(type) {
	case *mir.LocalValue, *mir.NameValue:
		ptr, err := lowerAddrOf(state, &mir.AddrOfValue{Source: value})
		return nil, ptr, err
	case *mir.UnaryValue:
		if v.Op == "copy" || v.Op == "take" || v.Op == "comptime" {
			return lowerInterfaceConcretePointer(state, v.Right, concreteType)
		}
	}
	if isAggregateType(state, concreteType) {
		return lowerAggregateValuePointer(state, value)
	}
	size, align, err := qbeScalarSizeAlign(concreteType)
	if err != nil {
		return nil, "", err
	}
	val, err := lowerValue(state, value)
	if err != nil {
		return nil, "", err
	}
	op, err := qbeStoreOp(concreteType)
	if err != nil {
		return nil, "", err
	}
	tmp := freshTemp(state, "iface_data")
	lines := []string{
		fmt.Sprintf("%s =l alloc%d %d", tmp, normalizeQBEAlign(align), size),
		fmt.Sprintf("%s %s, %s", op, val, tmp),
	}
	return lines, tmp, nil
}

func lowerInterfaceCall(state *moduleState, targetName string, targetType typeinfo.Type, call *mir.CallValue, field *mir.FieldValue) (string, error) {
	if len(call.Args) == 0 {
		return "", fmt.Errorf("interface call requires receiver")
	}
	recv := call.Args[0]
	slotPtr, err := lowerInterfaceSlotPointer(state, recv)
	if err != nil {
		return "", err
	}
	method, methodIndex, err := lookupInterfaceMethodDecl(state, recv.Type(), field.MemberName)
	if err != nil {
		return "", err
	}
	dataTmp := freshTemp(state, "iface_data")
	vtTmp := freshTemp(state, "iface_vt")
	vtAddr := freshTemp(state, "iface_vt_addr")
	fnSlot := freshTemp(state, "iface_fnslot")
	fnTmp := freshTemp(state, "iface_fn")
	lines := []string{
		fmt.Sprintf("%s =l loadl %s", dataTmp, slotPtr),
		fmt.Sprintf("%s =l add %s, 8", vtAddr, slotPtr),
		fmt.Sprintf("%s =l loadl %s", vtTmp, vtAddr),
	}
	if methodIndex > 0 {
		lines = append(lines, fmt.Sprintf("%s =l add %s, %d", fnSlot, vtTmp, methodIndex*8))
	} else {
		lines = append(lines, fmt.Sprintf("%s =l copy %s", fnSlot, vtTmp))
	}
	lines = append(lines, fmt.Sprintf("%s =l loadl %s", fnTmp, fnSlot))

	args := []string{fmt.Sprintf("l %s", dataTmp)}
	for i, arg := range call.Args[1:] {
		expected := typeinfo.Type(nil)
		if method != nil && i < len(method.Params) {
			expected = method.Params[i].Type
		}
		if expected == nil {
			expected = arg.Type()
		}
		atype, err := qbeABIType(state, expected)
		if err != nil {
			return "", err
		}
		aval, err := lowerValue(state, arg)
		if err != nil {
			return "", err
		}
		args = append(args, fmt.Sprintf("%s %s", atype, aval))
	}
	callText := fmt.Sprintf("call %s(%s)", fnTmp, strings.Join(args, ", "))
	if targetName == "" {
		lines = append(lines, callText)
		return strings.Join(lines, "\n\t"), nil
	}
	qtype, err := qbeABIType(state, targetType)
	if err != nil {
		return "", err
	}
	if qtype == "" {
		lines = append(lines, callText)
		return strings.Join(lines, "\n\t"), nil
	}
	if local := findLocalByName(state.fn, targetName); local != nil {
		if agg, ok := state.aggLocals[local.ID]; ok {
			tmp := freshTemp(state, "iface_ret")
			lines = append(lines,
				fmt.Sprintf("%s =%s %s", tmp, qtype, callText),
				fmt.Sprintf("blit %s, %s, %d", tmp, qbeLocalName(agg.PtrName), agg.Size),
			)
			return strings.Join(lines, "\n\t"), nil
		}
	}
	lines = append(lines, fmt.Sprintf("%s =%s %s", qbeLocalName(targetName), qtype, callText))
	return strings.Join(lines, "\n\t"), nil
}

func lowerInterfaceSlotPointer(state *moduleState, value mir.Value) (string, error) {
	switch v := value.(type) {
	case *mir.LocalValue:
		if value, ok := state.tempValues[v.LocalID]; ok && value != nil {
			return lowerValue(state, value)
		}
		if agg, ok := state.aggLocals[v.LocalID]; ok {
			return qbeLocalName(agg.PtrName), nil
		}
	case *mir.NameValue:
		if v.LinkName != "" {
			return "$" + sanitizeIdent(v.LinkName), nil
		}
		return "$" + qbeSymbol(state, v.Path), nil
	}
	return "", fmt.Errorf("unsupported interface receiver storage %T", value)
}

func ensureQBEInterfaceVTable(state *moduleState, target typeinfo.Type, value *mir.InterfaceValue) (string, error) {
	if state == nil || value == nil {
		return "", fmt.Errorf("invalid interface vtable request")
	}
	targetNamed, ok := target.(*typeinfo.NamedType)
	if !ok || targetNamed == nil {
		return "", fmt.Errorf("interface target must be named")
	}
	key := targetNamed.String() + "|" + typeinfo.FormatType(typeStringer{value.ConcreteType})
	if sym, ok := state.interfaceVTables[key]; ok {
		return sym, nil
	}
	methods, _, err := lookupInterfaceDecl(state, target)
	if err != nil {
		return "", err
	}
	sym := sanitizeIdent("vtable__" + qbeTypeName(state, targetNamed) + "__" + sanitizeType(value.ConcreteType))
	entries := make([]string, 0, len(methods.Methods))
	for i, method := range methods.Methods {
		if method == nil {
			continue
		}
		if i >= len(value.Methods) {
			return "", fmt.Errorf("missing interface method link for %s", method.Name)
		}
		wrap, err := ensureQBEInterfaceWrapper(state, targetNamed, method, value.ConcreteType, value.Methods[i])
		if err != nil {
			return "", err
		}
		entries = append(entries, "l $"+wrap)
	}
	fmt.Fprintf(state.deferredB, "data $%s = { %s }\n", sym, strings.Join(entries, ", "))
	state.interfaceVTables[key] = sym
	return sym, nil
}

func ensureQBEInterfaceWrapper(state *moduleState, iface *typeinfo.NamedType, method *mir.InterfaceMethodDecl, concrete typeinfo.Type, link mir.InterfaceMethodLink) (string, error) {
	key := iface.String() + "|" + sanitizeType(concrete) + "|" + method.Name
	name := sanitizeIdent("ifacewrap__" + qbeTypeName(state, iface) + "__" + sanitizeType(concrete) + "__" + method.Name)
	if _, ok := state.interfaceWrappers[key]; ok {
		return name, nil
	}
	ret, err := qbeABIType(state, method.Result)
	if err != nil {
		return "", err
	}
	params := []string{"l %data"}
	argNames := make([]string, 0, len(method.Params))
	for i, param := range method.Params {
		pty, err := qbeABIType(state, param.Type)
		if err != nil {
			return "", err
		}
		argName := fmt.Sprintf("%%arg%d", i)
		argNames = append(argNames, argName)
		params = append(params, fmt.Sprintf("%s %s", pty, argName))
	}
	var body []string
	callArgs := make([]string, 0, 1+len(argNames))
	recvArg, recvPrep, err := qbeInterfaceReceiverArg(state, concrete, link, method)
	if err != nil {
		return "", err
	}
	if recvPrep != "" {
		body = append(body, recvPrep)
	}
	callArgs = append(callArgs, recvArg)
	for i, param := range method.Params {
		pty, err := qbeABIType(state, param.Type)
		if err != nil {
			return "", err
		}
		callArgs = append(callArgs, fmt.Sprintf("%s %s", pty, argNames[i]))
	}
	callee := "$" + qbeSymbol(state, link.Path)
	if ret == "" {
		body = append(body, fmt.Sprintf("call %s(%s)", callee, strings.Join(callArgs, ", ")), "ret")
	} else {
		tmp := "%ret"
		body = append(body, fmt.Sprintf("%s =%s call %s(%s)", tmp, ret, callee, strings.Join(callArgs, ", ")), fmt.Sprintf("ret %s", tmp))
	}
	fmt.Fprintf(state.deferredB, "function")
	if ret != "" {
		fmt.Fprintf(state.deferredB, " %s", ret)
	}
	fmt.Fprintf(state.deferredB, " $%s(%s) {\n@entry\n", name, strings.Join(params, ", "))
	for _, line := range body {
		fmt.Fprintf(state.deferredB, "\t%s\n", line)
	}
	fmt.Fprintf(state.deferredB, "}\n")
	state.interfaceWrappers[key] = struct{}{}
	return name, nil
}

func qbeInterfaceReceiverArg(state *moduleState, concrete typeinfo.Type, link mir.InterfaceMethodLink, method *mir.InterfaceMethodDecl) (string, string, error) {
	callee := concrete
	if qbeIsPointerLike(concrete) {
		abi, err := qbeABIType(state, concrete)
		if err != nil {
			return "", "", err
		}
		return fmt.Sprintf("%s %%data", abi), "", nil
	}
	abi, err := qbeABIType(state, callee)
	if err != nil {
		return "", "", err
	}
	if isAggregateType(state, callee) {
		return fmt.Sprintf("%s %%data", abi), "", nil
	}
	op, qtype, err := qbeLoadOp(callee)
	if err != nil {
		return "", "", err
	}
	tmp := "%recv"
	_ = method
	_ = link
	return fmt.Sprintf("%s %s", abi, tmp), fmt.Sprintf("%s =%s %s %%data", tmp, qtype, op), nil
}

func lookupInterfaceDecl(state *moduleState, typ typeinfo.Type) (*mir.InterfaceTypeDecl, *typeinfo.NamedType, error) {
	named, ok := typ.(*typeinfo.NamedType)
	if !ok || named == nil {
		return nil, nil, fmt.Errorf("interface type must be named")
	}
	var mod *mir.Module
	if state.modules != nil {
		mod = state.modules[named.ModuleKey]
	}
	if mod == nil {
		mod = state.mod
	}
	if mod == nil {
		return nil, nil, fmt.Errorf("module for interface %s is not available", named.String())
	}
	for _, decl := range mod.Types {
		if decl != nil && decl.Named != nil && decl.Named.Name == named.Name && decl.Interface != nil {
			return decl.Interface, decl.Named, nil
		}
	}
	return nil, nil, fmt.Errorf("interface type %s is not available in qbe backend", named.String())
}

func lookupInterfaceMethodDecl(state *moduleState, typ typeinfo.Type, name string) (*mir.InterfaceMethodDecl, int, error) {
	iface, _, err := lookupInterfaceDecl(state, typ)
	if err != nil {
		return nil, -1, err
	}
	for i, method := range iface.Methods {
		if method != nil && method.Name == name {
			return method, i, nil
		}
	}
	return nil, -1, fmt.Errorf("interface method %s not found", name)
}

func sanitizeType(typ typeinfo.Type) string {
	return sanitizeIdent(strings.NewReplacer(
		"local:", "",
		"::", "__",
		"*", "ptr_",
		" ", "_",
		"?", "opt_",
		"!", "_",
		"/", "__",
	).Replace(typeinfo.FormatType(typeStringer{typ})))
}

func isUnionAggregate(typ typeinfo.Type) bool {
	switch t := typ.(type) {
	case *typeinfo.NamedType:
		return namedIsUnion(t)
	case *typeinfo.UnionType:
		return true
	case *typeinfo.OptionalType:
		return !optionalUsesNiche(t.Inner)
	default:
		return false
	}
}

func optionalUsesNiche(typ typeinfo.Type) bool {
	switch t := unwrapNamed(typ).(type) {
	case *typeinfo.PointerType, *typeinfo.RefType, *typeinfo.RawPtrType:
		return true
	case *typeinfo.BuiltinType:
		switch t.Name {
		case "bool", "char":
			return true
		}
	case *typeinfo.EnumType, *typeinfo.ErrorSetType:
		return true
	}
	return false
}

func lowerUnionAssign(state *moduleState, agg *aggregateLocal, value mir.Value) (string, error) {
	switch v := value.(type) {
	case *mir.UnaryValue:
		if v.Op == "copy" || v.Op == "take" || v.Op == "comptime" {
			return lowerUnionAssign(state, agg, v.Right)
		}
	case *mir.CastValue:
		if isUnionAggregate(v.Type()) {
			return lowerUnionAssign(state, agg, v.Left)
		}
	}
	if _, ok := unwrapNamed(agg.Type).(*typeinfo.OptionalType); ok {
		if _, isNone := value.(*mir.NoneValue); isNone {
			return fmt.Sprintf("storew 0, %s", qbeLocalName(agg.PtrName)), nil
		}
	}
	if isUnionAggregate(value.Type()) {
		src, err := lowerAggregateSource(state, value)
		if err != nil {
			return "", err
		}
		size, align, err := aggregateSizeAlign(state, agg.Type)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("blit %s, %s, %d", src, qbeLocalName(agg.PtrName), alignUpInt64(size, align)), nil
	}
	if isAggregateType(state, value.Type()) {
		src, err := lowerAggregateSource(state, value)
		if err != nil {
			return "", err
		}
		size, _, err := aggregateSizeAlign(state, value.Type())
		if err != nil {
			return "", err
		}
		info, err := unionLayoutInfo(state, agg.Type)
		if err != nil {
			return "", err
		}
		memberIndex := 1
		if _, ok := unwrapNamed(agg.Type).(*typeinfo.OptionalType); !ok {
			memberIndex, err = unionMemberIndex(info.Members, value.Type())
			if err != nil {
				return "", err
			}
		}
		lines := []string{fmt.Sprintf("storew %d, %s", memberIndex, qbeLocalName(agg.PtrName))}
		dst := qbeLocalName(agg.PtrName)
		if info.PayloadOffset != 0 {
			tmp := freshTemp(state, "unionpayload")
			lines = append(lines, fmt.Sprintf("%s =l add %s, %d", tmp, qbeLocalName(agg.PtrName), info.PayloadOffset))
			dst = tmp
		}
		lines = append(lines, fmt.Sprintf("blit %s, %s, %d", src, dst, size))
		return strings.Join(lines, "\n"), nil
	}
	val, err := lowerValue(state, value)
	if err != nil {
		return "", err
	}
	op, err := qbeStoreOp(value.Type())
	if err != nil {
		return "", err
	}
	info, err := unionLayoutInfo(state, agg.Type)
	if err != nil {
		return "", err
	}
	memberIndex := 1
	if _, ok := unwrapNamed(agg.Type).(*typeinfo.OptionalType); !ok {
		memberIndex, err = unionMemberIndex(info.Members, value.Type())
		if err != nil {
			return "", err
		}
	}
	lines := []string{fmt.Sprintf("storew %d, %s", memberIndex, qbeLocalName(agg.PtrName))}
	dst := qbeLocalName(agg.PtrName)
	if info.PayloadOffset != 0 {
		tmp := freshTemp(state, "unionpayload")
		lines = append(lines, fmt.Sprintf("%s =l add %s, %d", tmp, qbeLocalName(agg.PtrName), info.PayloadOffset))
		dst = tmp
	}
	if !qbeValueNeedsCopy(value) {
		qtype, err := qbeBaseType(value.Type())
		if err != nil {
			return "", err
		}
		tmp := freshTemp(state, "store")
		lines = append(lines, fmt.Sprintf("%s =%s %s", tmp, qtype, val))
		val = tmp
	}
	lines = append(lines, fmt.Sprintf("%s %s, %s", op, val, dst))
	return strings.Join(lines, "\n"), nil
}

// emitQBEStringConstant appends a QBE data section for a string literal to
// state.deferredB and returns the generated global symbol name.
func emitQBEStringConstant(state *moduleState, s string) string {
	idx := state.nextStrConst
	state.nextStrConst++
	sym := fmt.Sprintf("__ferret_str%d_%s", idx, sanitizeIdent(state.modulePrefix))
	// QBE data: bytes of the string followed by a NUL terminator.
	fmt.Fprintf(state.deferredB, "data $%s = { b %q, b 0 }\n", sym, s)
	return sym
}

func lowerAggregateCall(state *moduleState, agg *aggregateLocal, call *mir.CallValue) (string, error) {
	if agg == nil || call == nil {
		return "", fmt.Errorf("invalid aggregate call lowering")
	}
	if local, ok := call.Callee.(*mir.LocalValue); ok {
		if field, ok := state.tempValues[local.LocalID].(*mir.FieldValue); ok && len(call.Args) > 0 && isInterfaceAggregate(call.Args[0].Type()) {
			return lowerInterfaceCall(state, agg.Name, agg.Type, call, field)
		}
	}
	if field, ok := call.Callee.(*mir.FieldValue); ok && len(call.Args) > 0 && isInterfaceAggregate(call.Args[0].Type()) {
		return lowerInterfaceCall(state, agg.Name, agg.Type, call, field)
	}
	callee, err := lowerCallee(state, call.Callee)
	if err != nil {
		return "", err
	}
	if call.IsConstructor {
		return lowerConstructorCall(state, qbeLocalName(agg.PtrName), call, callee)
	}
	args := make([]string, 0, len(call.Args))
	for _, arg := range call.Args {
		atype, err := qbeABIType(state, arg.Type())
		if err != nil {
			return "", err
		}
		aval, err := lowerValue(state, arg)
		if err != nil {
			return "", err
		}
		args = append(args, fmt.Sprintf("%s %s", atype, aval))
	}
	temp := freshTemp(state, "aggret")
	abiType, err := qbeABIType(state, agg.Type)
	if err != nil {
		return "", err
	}
	lines := []string{
		fmt.Sprintf("%s =%s call %s(%s)", temp, abiType, callee, strings.Join(args, ", ")),
	}
	if temp != qbeLocalName(agg.PtrName) {
		lines = append(lines, fmt.Sprintf("blit %s, %s, %d", temp, qbeLocalName(agg.PtrName), agg.Size))
	}
	return strings.Join(lines, "\n\t"), nil
}

func lowerAggregateCompositeAssign(state *moduleState, agg *aggregateLocal, comp *mir.CompositeValue) (string, error) {
	// Array literal: positional items stored at successive element offsets.
	if arrType, ok := agg.Type.(*typeinfo.ArrayType); ok {
		elemSize, elemAlign, err := qbeScalarSizeAlign(arrType.Inner)
		if err != nil {
			// try inner as aggregate
			innerSz, innerAl, err2 := aggregateSizeAlign(state, arrType.Inner)
			if err2 != nil {
				return "", fmt.Errorf("unsupported array element type in composite literal: %s", arrType.Inner)
			}
			elemSize = innerSz
			elemAlign = innerAl
		}
		stride := alignUpInt64(elemSize, elemAlign)
		op, err := qbeStoreOp(arrType.Inner)
		if err != nil {
			return "", err
		}
		lines := make([]string, 0, len(comp.Items)*2)
		for i, item := range comp.Items {
			lowered, err := lowerValue(state, item.Value)
			if err != nil {
				return "", err
			}
			addr := qbeLocalName(agg.PtrName)
			offset := int64(i) * stride
			if offset != 0 {
				tmp := freshTemp(state, "addr")
				lines = append(lines, fmt.Sprintf("%s =l add %s, %d", tmp, qbeLocalName(agg.PtrName), offset))
				addr = tmp
			}
			lines = append(lines, fmt.Sprintf("%s %s, %s", op, lowered, addr))
		}
		return strings.Join(lines, "\n\t"), nil
	}

	// String / slice literal: items "ptr" and "len" stored at offsets 0 and 8.
	if _, ok := agg.Type.(*typeinfo.SliceType); ok {
		items := make(map[string]mir.Value, len(comp.Items))
		for _, item := range comp.Items {
			items[item.Name] = item.Value
		}
		ptrLowered, err := lowerValue(state, items["ptr"])
		if err != nil {
			return "", err
		}
		lenLowered, err := lowerValue(state, items["len"])
		if err != nil {
			return "", err
		}
		base := qbeLocalName(agg.PtrName)
		tmp := freshTemp(state, "len_addr")
		return fmt.Sprintf("storel %s, %s\n\t%s =l add %s, 8\n\tstorel %s, %s",
			ptrLowered, base, tmp, base, lenLowered, tmp), nil
	}
	if _, ok := agg.Type.(*typeinfo.StringType); ok {
		items := make(map[string]mir.Value, len(comp.Items))
		for _, item := range comp.Items {
			items[item.Name] = item.Value
		}
		ptrLowered, err := lowerValue(state, items["ptr"])
		if err != nil {
			return "", err
		}
		lenLowered, err := lowerValue(state, items["len"])
		if err != nil {
			return "", err
		}
		base := qbeLocalName(agg.PtrName)
		tmp := freshTemp(state, "len_addr")
		return fmt.Sprintf("storel %s, %s\n\t%s =l add %s, 8\n\tstorel %s, %s",
			ptrLowered, base, tmp, base, lenLowered, tmp), nil
	}

	structLayout, err := lookupStructLayout(state, agg.Type)
	if err != nil {
		return "", err
	}
	items := make(map[string]mir.Value, len(comp.Items))
	for _, item := range comp.Items {
		items[item.Name] = item.Value
	}
	lines := make([]string, 0, len(structLayout.Fields)*2)
	for _, field := range structLayout.Fields {
		if field == nil {
			continue
		}
		val, ok := items[field.Name]
		if !ok {
			continue
		}
		op, err := qbeStoreOp(field.Type)
		if err != nil {
			return "", err
		}
		addr := qbeLocalName(agg.PtrName)
		if field.Offset != 0 {
			tmp := freshTemp(state, "addr")
			lines = append(lines, fmt.Sprintf("%s =l add %s, %d", tmp, qbeLocalName(agg.PtrName), field.Offset))
			addr = tmp
		}
		lowered, err := lowerValue(state, val)
		if err != nil {
			return "", err
		}
		lines = append(lines, fmt.Sprintf("%s %s, %s", op, lowered, addr))
	}
	if len(comp.ConstructorPath) > 0 {
		ctor, err := lowerImplicitConstructorCall(state, qbeLocalName(agg.PtrName), comp.ConstructorPath)
		if err != nil {
			return "", err
		}
		if ctor != "" {
			lines = append(lines, ctor)
		}
	}
	return strings.Join(lines, "\n\t"), nil
}

func lowerAggregateSource(state *moduleState, value mir.Value) (string, error) {
	switch v := value.(type) {
	case *mir.LocalValue:
		return lowerValue(state, v)
	case *mir.NameValue:
		return lowerValue(state, v)
	case *mir.LoadValue:
		return lowerValue(state, v.Pointer)
	case *mir.FieldLoadValue:
		_, addr, _, err := lowerFieldAddress(state, v.Base, v.FieldIndex)
		if err != nil {
			return "", err
		}
		return addr, nil
	default:
		return "", fmt.Errorf("unsupported aggregate source %T", value)
	}
}

func lowerGlobalComposite(state *moduleState, typ typeinfo.Type, comp *mir.CompositeValue) (string, error) {
	if _, ok := typ.(*typeinfo.StringType); ok {
		return lowerGlobalStringLike(state, comp)
	}
	if _, ok := typ.(*typeinfo.SliceType); ok {
		return lowerGlobalStringLike(state, comp)
	}
	structLayout, err := lookupStructLayout(state, typ)
	if err != nil {
		return "", err
	}
	items := make(map[string]mir.Value, len(comp.Items))
	for _, item := range comp.Items {
		items[item.Name] = item.Value
	}
	parts := make([]string, 0, len(structLayout.Fields)*2)
	offset := int64(0)
	for _, field := range structLayout.Fields {
		if field == nil {
			continue
		}
		if field.Offset > offset {
			parts = append(parts, fmt.Sprintf("z %d", field.Offset-offset))
			offset = field.Offset
		}
		val, ok := items[field.Name]
		if !ok {
			parts = append(parts, fmt.Sprintf("z %d", field.Size))
			offset += field.Size
			continue
		}
		tok, lit, err := qbeDataItem(state, field.Type, val)
		if err != nil {
			return "", err
		}
		parts = append(parts, fmt.Sprintf("%s %s", tok, lit))
		offset += field.Size
	}
	if structLayout.Size > offset {
		parts = append(parts, fmt.Sprintf("z %d", structLayout.Size-offset))
	}
	return strings.Join(parts, ", "), nil
}

func lowerGlobalStringLike(state *moduleState, comp *mir.CompositeValue) (string, error) {
	items := make(map[string]mir.Value, len(comp.Items))
	for _, item := range comp.Items {
		items[item.Name] = item.Value
	}
	ptrTok, ptrLit, err := qbeDataItem(state, &typeinfo.RawPtrType{Inner: &typeinfo.BuiltinType{Name: "u8"}}, items["ptr"])
	if err != nil {
		return "", err
	}
	lenTok, lenLit, err := qbeDataItem(state, &typeinfo.BuiltinType{Name: "usize"}, items["len"])
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("%s %s, %s %s", ptrTok, ptrLit, lenTok, lenLit), nil
}

func qbeDataItem(state *moduleState, typ typeinfo.Type, value mir.Value) (string, string, error) {
	switch v := value.(type) {
	case *mir.NumberValue:
		return qbeDataLiteral(typ, v.Value)
	case *mir.BoolValue:
		if v.Value {
			return "b", "1", nil
		}
		return "b", "0", nil
	case *mir.NameValue:
		if v.LinkName != "" {
			return "l", "$" + sanitizeIdent(v.LinkName), nil
		}
		return "l", "$" + qbeSymbol(state, v.Path), nil
	default:
		return "", "", fmt.Errorf("unsupported data item %T", value)
	}
}

func prepareFunctionState(state *moduleState, fn *mir.Function) error {
	state.fn = fn
	state.aggLocals = make(map[int]*aggregateLocal)
	state.aggParams = make(map[int]struct{})
	state.scalarLocals = make(map[int]*scalarAllocaLocal)
	state.tempValues = make(map[int]mir.Value)
	state.nextTemp = 0
	state.pendingLines = nil
	for _, param := range fn.Params {
		if param == nil {
			continue
		}
		if isAggregateType(state, param.Type) {
			state.aggParams[param.LocalID] = struct{}{}
		}
	}
	for _, local := range fn.Locals {
		if local == nil {
			continue
		}
		if isAggregateType(state, local.Type) {
			agg := &aggregateLocal{
				ID:      local.ID,
				Name:    local.Name,
				Type:    local.Type,
				PtrName: local.Name,
			}
			if _, ok := state.aggParams[local.ID]; !ok {
				size, align, err := aggregateSizeAlign(state, local.Type)
				if err != nil {
					return err
				}
				agg.Size = size
				agg.Align = align
			}
			state.aggLocals[local.ID] = agg
			continue
		}
		if !local.Mutable && !qbeLocalAddressTaken(fn, local) {
			continue
		}
		qtype, err := qbeBaseType(local.Type)
		if err != nil || qtype == "" {
			continue
		}
		size, align, err := qbeScalarSizeAlign(local.Type)
		if err != nil {
			return err
		}
		state.scalarLocals[local.ID] = &scalarAllocaLocal{
			ID:      local.ID,
			Name:    local.Name,
			Type:    local.Type,
			PtrName: local.Name + "_slot",
			QType:   qtype,
			Align:   alignUpInt64(size, align),
		}
	}
	return nil
}

func qbeLocalAddressTaken(fn *mir.Function, local *mir.Local) bool {
	if fn == nil || local == nil {
		return false
	}
	for _, block := range fn.Blocks {
		if block == nil {
			continue
		}
		for _, instr := range block.Instructions {
			if qbeInstrHasAddrOfLocal(instr, local) {
				return true
			}
		}
		if qbeTermHasAddrOfLocal(block.Terminator, local) {
			return true
		}
	}
	return false
}

func qbeInstrHasAddrOfLocal(instr mir.Instr, local *mir.Local) bool {
	switch ins := instr.(type) {
	case *mir.BindInstr:
		return qbeValueHasAddrOfLocal(ins.Value, local)
	case *mir.ComputeInstr:
		return qbeValueHasAddrOfLocal(ins.Value, local)
	case *mir.AssignInstr:
		return qbeValueHasAddrOfLocal(ins.Value, local)
	case *mir.StoreInstr:
		return qbePlaceHasAddrOfLocal(ins.Target, local) || qbeValueHasAddrOfLocal(ins.Value, local)
	case *mir.StoreFieldInstr:
		return qbeValueHasAddrOfLocal(ins.Base, local) || qbeValueHasAddrOfLocal(ins.Value, local)
	case *mir.EvalInstr:
		return qbeValueHasAddrOfLocal(ins.Value, local)
	case *mir.DeferInstr:
		for _, nested := range ins.Body {
			if qbeInstrHasAddrOfLocal(nested, local) {
				return true
			}
		}
	case *mir.LockInstr:
		return qbeValueHasAddrOfLocal(ins.Value, local)
	}
	return false
}

func qbeTermHasAddrOfLocal(term mir.Terminator, local *mir.Local) bool {
	switch t := term.(type) {
	case *mir.BranchTerm:
		return qbeValueHasAddrOfLocal(t.Cond, local)
	case *mir.SwitchTerm:
		if qbeValueHasAddrOfLocal(t.Value, local) {
			return true
		}
		for _, c := range t.Cases {
			if qbeValueHasAddrOfLocal(c.Expr, local) {
				return true
			}
		}
	case *mir.ReturnTerm:
		return qbeValueHasAddrOfLocal(t.Value, local)
	case *mir.PanicTerm:
		return qbeValueHasAddrOfLocal(t.Value, local)
	}
	return false
}

func qbePlaceHasAddrOfLocal(place mir.Place, local *mir.Local) bool {
	switch p := place.(type) {
	case *mir.FieldPlace:
		return qbePlaceHasAddrOfLocal(p.Base, local)
	case *mir.IndexPlace:
		return qbePlaceHasAddrOfLocal(p.Base, local) || qbeValueHasAddrOfLocal(p.Index, local)
	case *mir.DerefPlace:
		return qbeValueHasAddrOfLocal(p.Pointer, local)
	default:
		return false
	}
}

func qbeValueHasAddrOfLocal(v mir.Value, local *mir.Local) bool {
	switch val := v.(type) {
	case *mir.AddrOfValue:
		switch src := val.Source.(type) {
		case *mir.LocalValue:
			if src.LocalID == local.ID {
				return true
			}
		case *mir.NameValue:
			return len(src.Path) == 1 && src.Path[0] == local.Name
		}
		return qbeValueHasAddrOfLocal(val.Source, local)
	case *mir.UnaryValue:
		return qbeValueHasAddrOfLocal(val.Right, local)
	case *mir.LoadValue:
		return qbeValueHasAddrOfLocal(val.Pointer, local)
	case *mir.BinaryValue:
		return qbeValueHasAddrOfLocal(val.Left, local) || qbeValueHasAddrOfLocal(val.Right, local)
	case *mir.PostfixValue:
		return qbeValueHasAddrOfLocal(val.Left, local)
	case *mir.CallValue:
		if qbeValueHasAddrOfLocal(val.Callee, local) {
			return true
		}
		for _, arg := range val.Args {
			if qbeValueHasAddrOfLocal(arg, local) {
				return true
			}
		}
	case *mir.FieldLoadValue:
		return qbeValueHasAddrOfLocal(val.Base, local)
	case *mir.FieldValue:
		return qbeValueHasAddrOfLocal(val.Base, local)
	case *mir.CastValue:
		return qbeValueHasAddrOfLocal(val.Left, local)
	case *mir.TypeTestValue:
		return qbeValueHasAddrOfLocal(val.Left, local)
	case *mir.CompositeValue:
		for _, item := range val.Items {
			if qbeValueHasAddrOfLocal(item.Value, local) {
				return true
			}
		}
	case *mir.InterfaceValue:
		return qbeValueHasAddrOfLocal(val.Value, local)
	case *mir.IndexValue:
		return qbeValueHasAddrOfLocal(val.Base, local) || qbeValueHasAddrOfLocal(val.Index, local)
	}
	return false
}

func entryPrelude(state *moduleState) []string {
	if state == nil || state.fn == nil {
		return nil
	}
	scalarIDs := make([]int, 0, len(state.scalarLocals))
	for id := range state.scalarLocals {
		scalarIDs = append(scalarIDs, id)
	}
	sort.Ints(scalarIDs)
	aggIDs := make([]int, 0, len(state.aggLocals))
	for id, agg := range state.aggLocals {
		if agg == nil {
			continue
		}
		if _, ok := state.aggParams[id]; ok {
			continue
		}
		aggIDs = append(aggIDs, id)
	}
	sort.Ints(aggIDs)
	lines := make([]string, 0, len(scalarIDs)+len(aggIDs))
	for _, id := range scalarIDs {
		sc := state.scalarLocals[id]
		lines = append(lines, fmt.Sprintf("%s =l alloc%d %d", qbeLocalName(sc.PtrName), normalizeQBEAlign(sc.Align), sc.Align))
	}
	for _, id := range aggIDs {
		agg := state.aggLocals[id]
		size := agg.Size
		align := agg.Align
		if size == 0 {
			size = 1
			align = 1
		}
		lines = append(lines, fmt.Sprintf("%s =l alloc%d %d", qbeLocalName(agg.PtrName), normalizeQBEAlign(align), size))
	}
	return lines
}

func lowerValue(state *moduleState, value mir.Value) (string, error) {
	switch v := value.(type) {
	case nil:
		return "", fmt.Errorf("nil value")
	case *mir.LocalValue:
		if agg, ok := state.aggLocals[v.LocalID]; ok {
			return qbeLocalName(agg.PtrName), nil
		}
		if sc, ok := state.scalarLocals[v.LocalID]; ok {
			op, qtype, err := qbeLoadOp(sc.Type)
			if err != nil {
				return "", err
			}
			tmp := freshTemp(state, "ld")
			state.pendingLines = append(state.pendingLines, fmt.Sprintf("%s =%s %s %s", tmp, qtype, op, qbeLocalName(sc.PtrName)))
			return tmp, nil
		}
		return qbeLocalName(localNameByID(state.fn, v.LocalID)), nil
	case *mir.NameValue:
		if len(v.Path) == 1 {
			if local := findLocalByName(state.fn, v.Path[0]); local != nil {
				if value, ok := state.tempValues[local.ID]; ok && value != nil {
					return lowerValue(state, value)
				}
				if agg, ok := state.aggLocals[local.ID]; ok {
					return qbeLocalName(agg.PtrName), nil
				}
				if sc, ok := state.scalarLocals[local.ID]; ok {
					op, qtype, err := qbeLoadOp(sc.Type)
					if err != nil {
						return "", err
					}
					tmp := freshTemp(state, "ld")
					state.pendingLines = append(state.pendingLines, fmt.Sprintf("%s =%s %s %s", tmp, qtype, op, qbeLocalName(sc.PtrName)))
					return tmp, nil
				}
				return qbeLocalName(local.Name), nil
			}
		}
		if _, ok := v.Type().(*typeinfo.FuncType); ok {
			if v.LinkName != "" {
				return "$" + sanitizeIdent(v.LinkName), nil
			}
			return "$" + qbeSymbol(state, v.Path), nil
		}
		if !isAggregateType(state, v.Type()) {
			op, qtype, err := qbeLoadOp(v.Type())
			if err == nil && qtype != "" {
				tmp := freshTemp(state, "ld")
				sym := "$" + qbeSymbol(state, v.Path)
				if v.LinkName != "" {
					sym = "$" + sanitizeIdent(v.LinkName)
				}
				state.pendingLines = append(state.pendingLines, fmt.Sprintf("%s =%s %s %s", tmp, qtype, op, sym))
				return tmp, nil
			}
		}
		if v.LinkName != "" {
			return "$" + sanitizeIdent(v.LinkName), nil
		}
		return "$" + qbeSymbol(state, v.Path), nil
	case *mir.NumberValue:
		return qbeNumberLiteral(v.Type(), v.Value)
	case *mir.BoolValue:
		if v.Value {
			return "1", nil
		}
		return "0", nil
	case *mir.StringValue:
		// String literals are *i8 — emit a data section and return its address.
		sym := emitQBEStringConstant(state, v.Value)
		return "$" + sym, nil
	case *mir.NoneValue:
		return "0", nil
	case *mir.UnaryValue:
		return lowerUnary(state, v)
	case *mir.AddrOfValue:
		return lowerAddrOf(state, v)
	case *mir.LoadValue:
		return "", fmt.Errorf("load value must be lowered in assignment/eval context")
	case *mir.BinaryValue:
		return lowerBinary(state, v)
	case *mir.CastValue:
		if isAggregateType(state, v.Type()) {
			expr, err := lowerCast(state, v)
			if err != nil {
				return "", err
			}
			abi, err := qbeABIType(state, v.Type())
			if err != nil {
				return "", err
			}
			tmp := freshTemp(state, "aggcast")
			state.pendingLines = append(state.pendingLines, fmt.Sprintf("%s =%s %s", tmp, abi, expr))
			return tmp, nil
		}
		return lowerCast(state, v)
	case *mir.TypeTestValue:
		return lowerTypeTest(state, v)
	case *mir.CallValue:
		if isAggregateType(state, v.Type()) {
			abi, err := qbeABIType(state, v.Type())
			if err != nil {
				return "", err
			}
			tmp := freshTemp(state, "aggcall")
			line, err := lowerCall(state, tmp[1:], v.Type(), v)
			if err != nil {
				return "", err
			}
			if line != "" {
				state.pendingLines = append(state.pendingLines, strings.Split(line, "\n\t")...)
			}
			_ = abi
			return tmp, nil
		}
		return "", fmt.Errorf("call value must be lowered in assignment/eval context")
	case *mir.FieldLoadValue:
		return "", fmt.Errorf("field load must be lowered in assignment context")
	case *mir.FieldValue:
		fieldIndex, err := qbeResolveFieldIndex(state, qbeFieldBaseType(state, v.Base), v.FieldIndex, v.MemberName)
		if err != nil {
			return "", err
		}
		lines, addr, _, err := lowerFieldAddress(state, v.Base, fieldIndex)
		if err != nil {
			return "", err
		}
		op, resultType, err := qbeLoadOp(v.Type())
		if err != nil {
			return "", err
		}
		tmp := freshTemp(state, "fld")
		state.pendingLines = append(state.pendingLines, lines...)
		state.pendingLines = append(state.pendingLines, fmt.Sprintf("%s =%s %s %s", tmp, resultType, op, addr))
		return tmp, nil
	case *mir.IndexValue:
		return "", fmt.Errorf("index value must be lowered in assignment context")
	default:
		return "", fmt.Errorf("unsupported MIR value %T", value)
	}
}

func qbeFieldBaseType(state *moduleState, value mir.Value) typeinfo.Type {
	if value == nil {
		return nil
	}
	if typ := value.Type(); typ != nil {
		return typ
	}
	if local, ok := value.(*mir.LocalValue); ok {
		return localTypeByID(state.fn, local.LocalID)
	}
	return nil
}

func lowerTypeTest(state *moduleState, v *mir.TypeTestValue) (string, error) {
	if v == nil {
		return "", fmt.Errorf("nil type test")
	}
	if _, isNone := v.Left.(*mir.NoneValue); isNone {
		if _, ok := unwrapNamed(v.Left.Type()).(*typeinfo.OptionalType); ok {
			return "0", nil
		}
	}
	if !isUnionAggregate(v.Left.Type()) {
		return "", fmt.Errorf("unsupported runtime type test on %s", typeinfo.FormatType(typeStringer{v.Left.Type()}))
	}
	info, err := unionLayoutInfo(state, v.Left.Type())
	if err != nil {
		return "", err
	}
	memberIndex := 0
	if opt, ok := unwrapNamed(v.Left.Type()).(*typeinfo.OptionalType); ok {
		if !typeinfo.Equal(opt.Inner, v.Target) {
			return "", fmt.Errorf("optional type test target %s does not match %s", typeinfo.FormatType(typeStringer{v.Target}), typeinfo.FormatType(typeStringer{opt.Inner}))
		}
		memberIndex = 1
	} else {
		memberIndex, err = unionMemberIndex(info.Members, v.Target)
		if err != nil {
			return "", err
		}
	}
	src, err := lowerAggregateSource(state, v.Left)
	if err != nil {
		return "", err
	}
	tag := freshTemp(state, "uniontag")
	state.pendingLines = append(state.pendingLines, fmt.Sprintf("%s =w loaduw %s", tag, src))
	cmp := freshTemp(state, "istype")
	state.pendingLines = append(state.pendingLines, fmt.Sprintf("%s =w ceqw %s, %d", cmp, tag, memberIndex))
	return cmp, nil
}

func lowerAddrOf(state *moduleState, v *mir.AddrOfValue) (string, error) {
	switch src := v.Source.(type) {
	case *mir.LocalValue:
		if agg, ok := state.aggLocals[src.LocalID]; ok {
			return qbeLocalName(agg.PtrName), nil
		}
		if sc, ok := state.scalarLocals[src.LocalID]; ok {
			return qbeLocalName(sc.PtrName), nil
		}
		return "", fmt.Errorf("addr_of on scalar local is not supported by qbe lowerer yet")
	case *mir.NameValue:
		if len(src.Path) == 1 {
			if local := findLocalByName(state.fn, src.Path[0]); local != nil {
				if agg, ok := state.aggLocals[local.ID]; ok {
					return qbeLocalName(agg.PtrName), nil
				}
				if sc, ok := state.scalarLocals[local.ID]; ok {
					return qbeLocalName(sc.PtrName), nil
				}
				return "", fmt.Errorf("addr_of on scalar SSA local is not supported by qbe lowerer yet")
			}
		}
		if src.LinkName != "" {
			return "$" + sanitizeIdent(src.LinkName), nil
		}
		return "$" + qbeSymbol(state, src.Path), nil
	default:
		return "", fmt.Errorf("unsupported addr_of source %T", v.Source)
	}
}

func lowerUnary(state *moduleState, v *mir.UnaryValue) (string, error) {
	right, err := lowerValue(state, v.Right)
	if err != nil {
		return "", err
	}
	switch v.Op {
	case "copy", "take", "comptime":
		return "copy " + right, nil
	case "-":
		return "neg " + right, nil
	case "!":
		suffix, err := qbeCompareSuffix(v.Right.Type())
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("ceq%s %s, 0", suffix, right), nil
	default:
		return "", fmt.Errorf("unsupported unary op %q", v.Op)
	}
}

func lowerBinary(state *moduleState, v *mir.BinaryValue) (string, error) {
	left, err := lowerValue(state, v.Left)
	if err != nil {
		return "", err
	}
	right, err := lowerValue(state, v.Right)
	if err != nil {
		return "", err
	}
	switch v.Op {
	case "+", "-", "*", "/", "%", "&&", "||":
		op, err := qbeBinaryOp(v.Op, v.Type())
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s %s, %s", op, left, right), nil
	case "==", "!=", "<", "<=", ">", ">=":
		op, err := qbeCompareOp(v.Op, v.Left.Type())
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s %s, %s", op, left, right), nil
	default:
		return "", fmt.Errorf("unsupported binary op %q", v.Op)
	}
}

func lowerCast(state *moduleState, v *mir.CastValue) (string, error) {
	if v == nil || v.Left == nil {
		return "", fmt.Errorf("invalid cast")
	}
	if _, ok := unwrapNamed(v.Type()).(*typeinfo.StringType); ok {
		return lowerStringCast(state, v.Left)
	}
	if isUnionAggregate(v.Left.Type()) && !isAggregateType(state, v.Type()) {
		srcPtr, err := lowerUnionSource(state, v.Left)
		if err != nil {
			return "", err
		}
		op, qtype, err := qbeLoadOp(v.Type())
		if err != nil {
			return "", err
		}
		tmp := freshTemp(state, "unioncast")
		state.pendingLines = append(state.pendingLines, fmt.Sprintf("%s =%s %s %s", tmp, qtype, op, srcPtr))
		return "copy " + tmp, nil
	}
	if isAggregateType(state, v.Left.Type()) && isAggregateType(state, v.Type()) {
		return lowerValue(state, v.Left)
	}
	srcVal, err := lowerValue(state, v.Left)
	if err != nil {
		return "", err
	}
	src := unwrapNamed(v.Left.Type())
	dst := unwrapNamed(v.Type())

	srcBuiltin, srcIsBuiltin := src.(*typeinfo.BuiltinType)
	dstBuiltin, dstIsBuiltin := dst.(*typeinfo.BuiltinType)
	if srcIsBuiltin && dstIsBuiltin {
		if srcBuiltin.Name == dstBuiltin.Name {
			return "copy " + srcVal, nil
		}
		if op, ok := qbeIntCastOp(srcBuiltin.Name, dstBuiltin.Name); ok {
			return fmt.Sprintf("%s %s", op, srcVal), nil
		}
		if op, ok := qbeFloatCastOp(srcBuiltin.Name, dstBuiltin.Name); ok {
			return fmt.Sprintf("%s %s", op, srcVal), nil
		}
	}
	if qbeIsPointerLike(dst) {
		return "copy " + srcVal, nil
	}
	return "", fmt.Errorf("unsupported cast from %s to %s", typeinfo.FormatType(typeStringer{v.Left.Type()}), typeinfo.FormatType(typeStringer{v.Type()}))
}

func lowerUnionSource(state *moduleState, value mir.Value) (string, error) {
	switch v := value.(type) {
	case *mir.UnaryValue:
		if v.Op == "copy" || v.Op == "take" || v.Op == "comptime" {
			return lowerUnionSource(state, v.Right)
		}
	case *mir.LocalValue, *mir.NameValue:
		src, err := lowerAggregateSource(state, value)
		if err != nil {
			return "", err
		}
		info, err := unionLayoutInfo(state, value.Type())
		if err != nil {
			return "", err
		}
		if info.PayloadOffset == 0 {
			return src, nil
		}
		tmp := freshTemp(state, "unionpayload")
		state.pendingLines = append(state.pendingLines, fmt.Sprintf("%s =l add %s, %d", tmp, src, info.PayloadOffset))
		return tmp, nil
	}
	return "", fmt.Errorf("unsupported union source %T", value)
}

type backendUnionLayout struct {
	Size          int64
	Align         int64
	PayloadOffset int64
	Members       []typeinfo.Type
}

func unionLayoutInfo(state *moduleState, typ typeinfo.Type) (*backendUnionLayout, error) {
	switch t := typ.(type) {
	case *typeinfo.NamedType:
		info, err := lookupNamedLayout(state, t)
		if err != nil {
			return nil, err
		}
		if info == nil || info.Union == nil {
			return nil, fmt.Errorf("type %s has no union layout", t)
		}
		return &backendUnionLayout{
			Size:          info.Size,
			Align:         info.Align,
			PayloadOffset: info.Union.PayloadOffset,
			Members:       unionMemberTypes(info.Union),
		}, nil
	case *typeinfo.OptionalType:
		payloadSize, payloadAlign, err := qbeScalarSizeAlign(t.Inner)
		if err != nil {
			payloadSize, payloadAlign, err = aggregateSizeAlign(state, t.Inner)
			if err != nil {
				return nil, err
			}
		}
		payloadOffset := alignUpInt64(4, payloadAlign)
		align := payloadAlign
		if align < 4 {
			align = 4
		}
		size := alignUpInt64(payloadOffset+payloadSize, align)
		return &backendUnionLayout{
			Size:          size,
			Align:         align,
			PayloadOffset: payloadOffset,
			Members:       []typeinfo.Type{t.Inner},
		}, nil
	case *typeinfo.UnionType:
		payloadSize := int64(0)
		payloadAlign := int64(1)
		for _, member := range t.Members {
			size, align, err := aggregateSizeAlign(state, member)
			if err != nil {
				return nil, err
			}
			if size > payloadSize {
				payloadSize = size
			}
			if align > payloadAlign {
				payloadAlign = align
			}
		}
		payloadOffset := alignUpInt64(4, payloadAlign)
		align := payloadAlign
		if align < 4 {
			align = 4
		}
		size := alignUpInt64(payloadOffset+payloadSize, align)
		return &backendUnionLayout{Size: size, Align: align, PayloadOffset: payloadOffset, Members: t.Members}, nil
	default:
		return nil, fmt.Errorf("type %s has no union layout", typeinfo.FormatType(typeStringer{typ}))
	}
}

func unionMemberIndex(members []typeinfo.Type, memberType typeinfo.Type) (int, error) {
	exact := -1
	assignable := -1
	for i, member := range members {
		if typeinfo.Equal(member, memberType) {
			if exact >= 0 {
				return -1, fmt.Errorf("ambiguous union member for %s", typeinfo.FormatType(typeStringer{memberType}))
			}
			exact = i
			continue
		}
		if typeinfo.Assignable(member, memberType) {
			if assignable >= 0 {
				assignable = -2
			} else {
				assignable = i
			}
		}
	}
	if exact >= 0 {
		return exact, nil
	}
	if assignable >= 0 {
		return assignable, nil
	}
	return -1, fmt.Errorf("no union member for %s", typeinfo.FormatType(typeStringer{memberType}))
}

func unionMemberTypes(info *layout.UnionLayout) []typeinfo.Type {
	if info == nil {
		return nil
	}
	out := make([]typeinfo.Type, 0, len(info.Members))
	for _, member := range info.Members {
		if member != nil {
			out = append(out, member.Type)
		}
	}
	return out
}

func lowerStringCast(state *moduleState, value mir.Value) (string, error) {
	srcVal, err := lowerValue(state, value)
	if err != nil {
		return "", err
	}
	src := unwrapNamed(value.Type())
	srcBuiltin, ok := src.(*typeinfo.BuiltinType)
	if !ok {
		return "", fmt.Errorf("unsupported string cast source %s", typeinfo.FormatType(typeStringer{value.Type()}))
	}
	switch srcBuiltin.Name {
	case "i8", "i16", "i32":
		op, _ := qbeIntCastOp(srcBuiltin.Name, "i64")
		return fmt.Sprintf("call $global__i64_str(l %s)", qbeOperandWithTemp(state, "l", joinQBEValue(op, srcVal))), nil
	case "i64", "isize":
		if srcBuiltin.Name == "isize" {
			op, _ := qbeIntCastOp(srcBuiltin.Name, "i64")
			return fmt.Sprintf("call $global__i64_str(l %s)", qbeOperandWithTemp(state, "l", joinQBEValue(op, srcVal))), nil
		}
		return fmt.Sprintf("call $global__i64_str(l %s)", srcVal), nil
	case "u8", "u16", "u32", "bool", "char":
		op, _ := qbeIntCastOp(srcBuiltin.Name, "u64")
		return fmt.Sprintf("call $global__u64_str(l %s)", qbeOperandWithTemp(state, "l", joinQBEValue(op, srcVal))), nil
	case "u64", "usize":
		if srcBuiltin.Name == "usize" {
			op, _ := qbeIntCastOp(srcBuiltin.Name, "u64")
			return fmt.Sprintf("call $global__u64_str(l %s)", qbeOperandWithTemp(state, "l", joinQBEValue(op, srcVal))), nil
		}
		return fmt.Sprintf("call $global__u64_str(l %s)", srcVal), nil
	case "f32":
		op, _ := qbeFloatCastOp("f32", "f64")
		return fmt.Sprintf("call $global__f64_str(d %s)", qbeOperandWithTemp(state, "d", joinQBEValue(op, srcVal))), nil
	case "f64":
		return fmt.Sprintf("call $global__f64_str(d %s)", srcVal), nil
	default:
		return "", fmt.Errorf("unsupported string cast source %s", srcBuiltin.Name)
	}
}

func joinQBEValue(op string, value string) string {
	if op == "" || op == "copy" {
		return value
	}
	return op + " " + value
}

func qbeOperandWithTemp(state *moduleState, qtype string, expr string) string {
	if !strings.Contains(expr, " ") || strings.HasPrefix(expr, "%") || strings.HasPrefix(expr, "$") || expr == "0" || expr == "1" {
		return expr
	}
	tmp := freshTemp(state, "cast")
	state.pendingLines = append(state.pendingLines, fmt.Sprintf("%s =%s %s", tmp, qtype, expr))
	return tmp
}

func lowerCallee(state *moduleState, value mir.Value) (string, error) {
	switch v := value.(type) {
	case *mir.NameValue:
		if v.LinkName != "" {
			return "$" + sanitizeIdent(v.LinkName), nil
		}
		return "$" + qbeSymbol(state, v.Path), nil
	default:
		return "", fmt.Errorf("unsupported call callee %T", value)
	}
}

func findLocalByName(fn *mir.Function, name string) *mir.Local {
	if fn == nil {
		return nil
	}
	for _, local := range fn.Locals {
		if local != nil && local.Name == name {
			return local
		}
	}
	return nil
}

func findLocalByID(fn *mir.Function, id int) *mir.Local {
	if fn == nil {
		return nil
	}
	for _, local := range fn.Locals {
		if local != nil && local.ID == id {
			return local
		}
	}
	return nil
}

func resolveQBETempValue(state *moduleState, value mir.Value) (mir.Value, bool) {
	switch v := value.(type) {
	case *mir.LocalValue:
		repl, ok := state.tempValues[v.LocalID]
		return repl, ok && repl != nil
	case *mir.NameValue:
		if len(v.Path) == 1 {
			if local := findLocalByName(state.fn, v.Path[0]); local != nil {
				repl, ok := state.tempValues[local.ID]
				return repl, ok && repl != nil
			}
		}
	}
	return nil, false
}

func localNameByID(fn *mir.Function, id int) string {
	if fn == nil {
		return fmt.Sprintf("t%d", id)
	}
	for _, local := range fn.Locals {
		if local != nil && local.ID == id {
			return local.Name
		}
	}
	return fmt.Sprintf("t%d", id)
}

func localTypeByID(fn *mir.Function, id int) typeinfo.Type {
	if fn == nil {
		return typeinfo.UnknownType{}
	}
	for _, local := range fn.Locals {
		if local != nil && local.ID == id {
			return local.Type
		}
	}
	return typeinfo.UnknownType{}
}

func isAggregateType(state *moduleState, typ typeinfo.Type) bool {
	if typ == nil {
		return false
	}
	if _, err := qbeBaseType(typ); err == nil {
		return false
	}
	_, _, err := aggregateSizeAlign(state, typ)
	return err == nil
}

func aggregateSizeAlign(state *moduleState, typ typeinfo.Type) (int64, int64, error) {
	switch t := typ.(type) {
	case *typeinfo.BuiltinType:
		return 0, 0, fmt.Errorf("unsupported aggregate builtin %s", t.Name)
	case *typeinfo.ArrayType:
		if t.Len < 0 {
			return 0, 0, fmt.Errorf("array with unknown length")
		}
		elemSize, elemAlign, err := qbeScalarSizeAlign(t.Inner)
		if err != nil {
			// try inner as aggregate
			inner, innerAl, err2 := aggregateSizeAlign(state, t.Inner)
			if err2 != nil {
				return 0, 0, fmt.Errorf("unsupported array element type %s", t.Inner)
			}
			stride := alignUpInt64(inner, innerAl)
			return stride * t.Len, innerAl, nil
		}
		stride := alignUpInt64(elemSize, elemAlign)
		return stride * t.Len, elemAlign, nil
	case *typeinfo.StringType:
		return 16, 8, nil
	case *typeinfo.SliceType:
		// str / []T: { ptr *T, len usize } — 16 bytes, 8-byte aligned.
		return 16, 8, nil
	case *typeinfo.OptionalType:
		if optionalUsesNiche(t.Inner) {
			return 0, 0, fmt.Errorf("optional %s uses niche layout", t.Inner)
		}
		info, err := unionLayoutInfo(state, typ)
		if err != nil {
			return 0, 0, err
		}
		return info.Size, info.Align, nil
	case *typeinfo.NamedType:
		info, err := lookupNamedLayout(state, t)
		if err != nil {
			return 0, 0, err
		}
		if info == nil || !info.Known {
			return 0, 0, fmt.Errorf("unknown aggregate layout for %s", t.String())
		}
		return info.Size, info.Align, nil
	default:
		return 0, 0, fmt.Errorf("unsupported aggregate type %s", typeinfo.FormatType(typeStringer{typ}))
	}
}

func lookupNamedLayout(state *moduleState, named *typeinfo.NamedType) (*layout.TypeLayout, error) {
	if named == nil {
		return nil, fmt.Errorf("nil named type")
	}
	if state != nil {
		if state.layouts != nil {
			if lm, ok := state.layouts[named.ModuleKey]; ok && lm != nil {
				if info, ok := lm.Lookup(named.Name); ok {
					return info, nil
				}
			}
		}
		if state.layout != nil && state.mod != nil && named.ModuleKey == state.mod.Key {
			if info, ok := state.layout.Lookup(named.Name); ok {
				return info, nil
			}
		}
	}
	return nil, fmt.Errorf("layout for named type %s is not available in qbe backend", named.String())
}

func lookupStructLayout(state *moduleState, typ typeinfo.Type) (*layout.StructLayout, error) {
	switch t := typ.(type) {
	case *typeinfo.BuiltinType:
		return nil, fmt.Errorf("builtin %s is not a struct layout", t.Name)
	case *typeinfo.NamedType:
		info, err := lookupNamedLayout(state, t)
		if err != nil {
			return nil, err
		}
		if info == nil || info.Struct == nil {
			return nil, fmt.Errorf("type %s is not a struct layout", t.String())
		}
		return info.Struct, nil
	case *typeinfo.PointerType:
		return lookupStructLayout(state, t.Inner)
	case *typeinfo.RefType:
		return lookupStructLayout(state, t.Inner)
	case *typeinfo.RawPtrType:
		return lookupStructLayout(state, t.Inner)
	default:
		return nil, fmt.Errorf("unsupported struct base type %s", typeinfo.FormatType(typeStringer{typ}))
	}
}

func qbeStructBody(state *moduleState, st *layout.StructLayout) (string, error) {
	parts := make([]string, 0, len(st.Fields)*2)
	offset := int64(0)
	for _, field := range st.Fields {
		if field == nil {
			continue
		}
		if field.Offset > offset {
			parts = append(parts, fmt.Sprintf("b %d", field.Offset-offset))
			offset = field.Offset
		}
		sub, err := qbeAggregateSubType(state, field.Type)
		if err != nil {
			return "", err
		}
		parts = append(parts, sub)
		offset += field.Size
	}
	if st.Size > offset {
		parts = append(parts, fmt.Sprintf("b %d", st.Size-offset))
	}
	return strings.Join(parts, ", "), nil
}

func qbeAggregateSubType(state *moduleState, typ typeinfo.Type) (string, error) {
	if named, ok := typ.(*typeinfo.NamedType); ok {
		info, err := lookupNamedLayout(state, named)
		if err == nil && info != nil && info.Known && (info.Struct != nil || namedIsUnion(named) || namedIsInterface(named)) {
			return ":" + qbeTypeName(state, named), nil
		}
	}
	if opt, ok := typ.(*typeinfo.OptionalType); ok {
		if !optionalUsesNiche(opt.Inner) {
			return fmt.Sprintf("b %d", mustAggregateSize(state, typ)), nil
		}
	}
	return qbeExtType(typ)
}

func qbeExtType(typ typeinfo.Type) (string, error) {
	switch base := unwrapNamed(typ).(type) {
	case *typeinfo.BuiltinType:
		switch base.Name {
		case "bool", "u8", "i8":
			return "b", nil
		case "u16", "i16":
			return "h", nil
		case "u32", "i32", "char":
			return "w", nil
		case "u64", "i64", "usize", "isize":
			return "l", nil
		case "f32":
			return "s", nil
		case "f64":
			return "d", nil
		}
	case *typeinfo.PointerType, *typeinfo.RefType, *typeinfo.RawPtrType:
		return "l", nil
	}
	return "", fmt.Errorf("unsupported aggregate member type %s", typeinfo.FormatType(typeStringer{typ}))
}

func qbeBaseType(typ typeinfo.Type) (string, error) {
	switch base := unwrapNamed(typ).(type) {
	case *typeinfo.BuiltinType:
		switch base.Name {
		case "bool", "i8", "i16", "i32", "u8", "u16", "u32", "char":
			return "w", nil
		case "i64", "u64", "isize", "usize":
			return "l", nil
		case "f32":
			return "s", nil
		case "f64":
			return "d", nil
		case "void":
			return "", nil
		}
	case *typeinfo.PointerType, *typeinfo.RefType, *typeinfo.RawPtrType:
		return "l", nil
	}
	return "", fmt.Errorf("unsupported qbe base type %s", typeinfo.FormatType(typeStringer{typ}))
}

func qbeABIType(state *moduleState, typ typeinfo.Type) (string, error) {
	switch t := typ.(type) {
	case *typeinfo.NamedType:
		if info, err := lookupNamedLayout(state, t); err == nil && info != nil && info.Known && (info.Struct != nil || namedIsUnion(t) || namedIsInterface(t)) {
			return ":" + qbeTypeName(state, t), nil
		}
	case *typeinfo.OptionalType:
		if !optionalUsesNiche(t.Inner) {
			return fmt.Sprintf(":__ferret_opt_%d", mustAggregateSize(state, typ)), nil
		}
	case *typeinfo.StringType:
		return ":__ferret_slice", nil
	case *typeinfo.SliceType:
		_ = t
		return ":__ferret_slice", nil
	}
	return qbeBaseType(typ)
}

func mustAggregateSize(state *moduleState, typ typeinfo.Type) int64 {
	size, _, err := aggregateSizeAlign(state, typ)
	if err != nil {
		return 0
	}
	return size
}

func namedIsUnion(named *typeinfo.NamedType) bool {
	if named == nil || named.Decl == nil {
		return false
	}
	_, ok := named.Decl.Type.(*ast.UnionType)
	return ok
}

func namedIsInterface(named *typeinfo.NamedType) bool {
	if named == nil || named.Decl == nil {
		return false
	}
	_, ok := named.Decl.Type.(*ast.InterfaceType)
	return ok
}

func qbeLoadOp(typ typeinfo.Type) (string, string, error) {
	switch base := unwrapNamed(typ).(type) {
	case *typeinfo.BuiltinType:
		switch base.Name {
		case "bool", "u8":
			return "loadub", "w", nil
		case "i8":
			return "loadsb", "w", nil
		case "u16":
			return "loaduh", "w", nil
		case "i16":
			return "loadsh", "w", nil
		case "u32", "i32", "char":
			return "loadw", "w", nil
		case "u64", "i64", "usize", "isize":
			return "loadl", "l", nil
		case "f32":
			return "loads", "s", nil
		case "f64":
			return "loadd", "d", nil
		}
	case *typeinfo.PointerType, *typeinfo.RefType, *typeinfo.RawPtrType:
		return "loadl", "l", nil
	}
	return "", "", fmt.Errorf("unsupported load type %s", typeinfo.FormatType(typeStringer{typ}))
}

func qbeStoreOp(typ typeinfo.Type) (string, error) {
	switch base := unwrapNamed(typ).(type) {
	case *typeinfo.BuiltinType:
		switch base.Name {
		case "bool", "u8", "i8":
			return "storeb", nil
		case "u16", "i16":
			return "storeh", nil
		case "u32", "i32", "char":
			return "storew", nil
		case "u64", "i64", "usize", "isize":
			return "storel", nil
		case "f32":
			return "stores", nil
		case "f64":
			return "stored", nil
		}
	case *typeinfo.PointerType, *typeinfo.RefType, *typeinfo.RawPtrType:
		return "storel", nil
	}
	return "", fmt.Errorf("unsupported store type %s", typeinfo.FormatType(typeStringer{typ}))
}

func qbeNumberLiteral(typ typeinfo.Type, lit string) (string, error) {
	switch base := unwrapNamed(typ).(type) {
	case *typeinfo.BuiltinType:
		switch base.Name {
		case "f32":
			return "s_" + lit, nil
		case "f64":
			return "d_" + lit, nil
		default:
			return lit, nil
		}
	case *typeinfo.PointerType, *typeinfo.RefType, *typeinfo.RawPtrType:
		return lit, nil
	}
	return "", fmt.Errorf("unsupported numeric literal type %s", typeinfo.FormatType(typeStringer{typ}))
}

func qbeDataLiteral(typ typeinfo.Type, lit string) (string, string, error) {
	tok, err := qbeExtType(typ)
	if err != nil {
		return "", "", err
	}
	value, err := qbeNumberLiteral(typ, lit)
	if err != nil {
		return "", "", err
	}
	return tok, value, nil
}

func qbeBinaryOp(op string, typ typeinfo.Type) (string, error) {
	switch op {
	case "+":
		return "add", nil
	case "-":
		return "sub", nil
	case "*":
		return "mul", nil
	case "/":
		if base, _ := qbeBaseType(typ); base == "w" || base == "l" {
			return "div", nil
		}
		return "div", nil
	case "%":
		return "rem", nil
	case "&&":
		return "and", nil
	case "||":
		return "or", nil
	default:
		return "", fmt.Errorf("unsupported qbe op %q", op)
	}
}

func qbeCompareSuffix(typ typeinfo.Type) (string, error) {
	switch base, err := qbeBaseType(typ); {
	case err != nil:
		return "", err
	case base == "w":
		return "w", nil
	case base == "l":
		return "l", nil
	case base == "s":
		return "s", nil
	case base == "d":
		return "d", nil
	default:
		return "", fmt.Errorf("unsupported qbe compare type %s", typeinfo.FormatType(typeStringer{typ}))
	}
}

func qbeCompareOp(op string, typ typeinfo.Type) (string, error) {
	suffix, err := qbeCompareSuffix(typ)
	if err != nil {
		return "", err
	}
	baseType, _ := qbeBaseType(typ)
	isFloat := baseType == "s" || baseType == "d"
	signedPrefix := "cs"
	if isFloat {
		signedPrefix = "c"
	}
	switch op {
	case "==":
		return "ceq" + suffix, nil
	case "!=":
		return "cne" + suffix, nil
	case "<":
		if isFloat {
			return "clt" + suffix, nil
		}
		return signedPrefix + "lt" + suffix, nil
	case "<=":
		if isFloat {
			return "cle" + suffix, nil
		}
		return signedPrefix + "le" + suffix, nil
	case ">":
		if isFloat {
			return "cgt" + suffix, nil
		}
		return signedPrefix + "gt" + suffix, nil
	case ">=":
		if isFloat {
			return "cge" + suffix, nil
		}
		return signedPrefix + "ge" + suffix, nil
	default:
		return "", fmt.Errorf("unsupported compare op %q", op)
	}
}

