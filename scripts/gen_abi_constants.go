	buf.WriteString(fmt.Sprintf("export const FIELD_INFO_OFFSET_OFFSET = %d;\n", runtimeabi.FieldInfoOffsetOffset))
	buf.WriteString(fmt.Sprintf("export const FIELD_INFO_TYPE_OFFSET = %d;\n", runtimeabi.FieldInfoTypeOffset))
