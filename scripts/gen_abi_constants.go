	buf.WriteString(fmt.Sprintf("export const SLICE_LEN_OFFSET = %d;\n", runtimeabi.SliceLenOffset))
	buf.WriteString(fmt.Sprintf("export const SLICE_CAP_OFFSET = %d;\n", runtimeabi.SliceCapOffset))
	buf.WriteString(fmt.Sprintf("export const SLICE_ELEM_SIZE_OFFSET = %d;\n", runtimeabi.SliceElemSizeOffset))
	buf.WriteString(fmt.Sprintf("export const SLICE_ELEM_TYPE_OFFSET = %d;\n", runtimeabi.SliceElemTypeOffset))
	buf.WriteString(fmt.Sprintf("export const SLICE_HEADER_SIZE = %d;\n", runtimeabi.SliceHeaderSize))
	buf.WriteString(fmt.Sprintf("export const INTERFACE_DATA_OFFSET = %d;\n", runtimeabi.InterfaceDataOffset))
	buf.WriteString(fmt.Sprintf("export const INTERFACE_EXTRA_OFFSET = %d;\n", runtimeabi.InterfaceExtraOffset))
	buf.WriteString(fmt.Sprintf("export const INTERFACE_SIZE = %d;\n", runtimeabi.InterfaceSize))
	buf.WriteString(fmt.Sprintf("export const UNION_TAG_SIZE = %d;\n", runtimeabi.UnionTagSize))
	buf.WriteString(fmt.Sprintf("export const UNION_PTR_OFFSET = %d;\n", runtimeabi.UnionPtrOffset))
